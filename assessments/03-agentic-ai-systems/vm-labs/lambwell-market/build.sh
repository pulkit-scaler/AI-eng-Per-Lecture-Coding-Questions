#!/bin/bash
# Regenerate setup/scripts/setup_script.sh from the template plus app/ and
# service/, verify every invariant this pack depends on, then stage
# dist/Setup.zip and dist/TestCase.zip from a clean directory.
#
# Both zips carry a scripts/ AND a data/ folder at the root; the platform
# rejects the older scripts-only shape.
set -euo pipefail

DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$DIR"

echo "=== [1/6] expanding setup template ==="
python3 - <<'PY'
import pathlib, re, sys

tpl = pathlib.Path("setup/setup_script.template.sh").read_text()

def expand(match):
    path = pathlib.Path(match.group(1))
    if not path.is_file():
        sys.exit("missing source file referenced by template: %s" % path)
    return path.read_text().rstrip("\n")

out, n = re.subn(r"@@FILE:([^@]+)@@", expand, tpl)
if "@@FILE:" in out:
    sys.exit("unexpanded marker left in generated setup script")
header = "# GENERATED by build.sh from setup/setup_script.template.sh - do not hand-edit.\n"
lines = out.split("\n")
out = lines[0] + "\n" + header + "\n".join(lines[1:])
pathlib.Path("setup/scripts/setup_script.sh").write_text(out)
print("  inlined %d source files" % n)
PY
chmod +x setup/scripts/setup_script.sh
bash -n setup/scripts/setup_script.sh
echo "  setup_script.sh syntax OK"

echo "=== [2/6] checking the pack against its own numbers ==="
python3 - <<'CONSISTCHK'
import importlib.util, pathlib, re, sys

site = pathlib.Path("service/marketsite.py").read_text()
gen = pathlib.Path("gen_tests.sh").read_text()
statement = pathlib.Path("problem-statement.md").read_text()

spec = importlib.util.spec_from_file_location("site", "app/market_kit/site.py")
kit = importlib.util.module_from_spec(spec)
spec.loader.exec_module(kit)

# The credentials the kit publishes have to be the ones the site accepts, or the
# session step cannot pass however it is written.
for name in ("LOGIN_USER", "LOGIN_PASSWORD"):
    found = re.search(r'^%s = "([^"]+)"$' % name, site, re.M)
    if not found:
        sys.exit("the site does not define %s" % name)
    if found.group(1) != getattr(kit, name):
        sys.exit("the site and the kit disagree about %s" % name)
print("  the site and the kit agree on the trader credentials")

# The crawl delay in robots.txt has to be the one the kit asks for, or a harvest
# that obeys the kit still fails the pace check.
found = re.search(r"^Crawl-delay:\s*([\d.]+)$", site, re.M)
if not found:
    sys.exit("robots.txt does not state a crawl delay")
if float(found.group(1)) != float(kit.MIN_INTERVAL):
    sys.exit("robots.txt asks for %s and the kit says %s"
             % (found.group(1), kit.MIN_INTERVAL))
print("  robots.txt and the kit agree on the pace (%ss)" % kit.MIN_INTERVAL)

# There has to be a disallowed path, and the site has to actually serve it -
# otherwise the check that nothing asked for it is vacuous.
if "Disallow: /private/" not in site:
    sys.exit("robots.txt disallows nothing, so the check has nothing to prove")
if 'path.startswith("/private/")' not in site:
    sys.exit("the site does not serve the disallowed path, so a harvest that "
             "asked for it would not be recorded")
print("  the disallowed path exists and is served, so asking for it is visible")

# The feed has to need more than one page, or scrolling to the end proves
# nothing.
total = int(re.search(r"^FEED_TOTAL = (\d+)$", site, re.M).group(1))
page = int(re.search(r"^FEED_PAGE = (\d+)$", site, re.M).group(1))
if total <= page:
    sys.exit("the feed fits in one page, so there is nothing to scroll for")
print("  the feed is %d lots in pages of %d, so it takes %d fetches"
      % (total, page, -(-total // page) + 1))

# The stall table has to finish rendering late enough that reading it early is
# actually wrong.
render = int(re.search(r"^STALL_RENDER_MS = (\d+)$", site, re.M).group(1))
if render < 500:
    sys.exit("the stall table renders in %dms, which is too fast for reading it "
             "early to be a mistake" % render)
if render >= kit.SETTLE_MS:
    sys.exit("the stall table takes %dms to render and the kit allows only %dms"
             % (render, kit.SETTLE_MS))
print("  the stall table renders over %dms, inside a %dms settle allowance"
      % (render, kit.SETTLE_MS))

# The checks must read their expectations from the site rather than hardcode
# them, or a change to the market silently invalidates them.
for token in ("expect_field", "log_field", "tokens_issued"):
    if token not in gen:
        sys.exit("the checks do not use %s, so they are not reading the site" % token)
print("  the checks read what to expect from the site itself")

# The credentials are published to the learner and must appear in the statement.
if kit.LOGIN_USER not in statement:
    sys.exit("the statement never gives the learner the trader username")
print("  the statement publishes the trader account")
CONSISTCHK

echo "=== [2b/6] checking the detached deps job closes over its variables ==="
python3 - <<'DEPSVARCHK'
import pathlib, re, sys

src = pathlib.Path("setup/setup_script.template.sh").read_text()
try:
    body = src[src.index("cat <<'DEPSJOB'"):src.index("\nDEPSJOB\n")]
    prelude = src[src.index('echo "DEPS_STATE='):src.index("cat <<'DEPSJOB'")]
except ValueError:
    sys.exit("could not locate the deps job in the template")

# The heredoc is QUOTED, so nothing in the body is expanded at build time. Any
# variable it names must be echoed into the prelude or assigned in the body, or
# it expands to nothing on the VM - and since every path here is absolute, that
# silently retargets the work at the filesystem root. This shipped once: the
# browser went to /.cache/ms-playwright instead of the learner home.
defined = set(re.findall(r'echo "(\w+)=', prelude))
defined |= set(re.findall(r'^\s*(?:export )?(\w+)=', body, re.M))
defined |= set(re.findall(r'^for (\w+) in', body, re.M))
inherited = {"SECONDS", "PATH", "HOME", "IFS", "PWD", "UID"}

used = set(re.findall(r'\$\{(\w+)', body)) | set(re.findall(r'\$([A-Z][A-Z0-9_]+)', body))
missing = sorted(used - defined - inherited)
if missing:
    print("  ERROR: the deps job references variables its prelude never defines:")
    for name in missing:
        print("    %s  -> expands to nothing; every path built from it targets /" % name)
    sys.exit(1)
print("  every variable the deps job uses is closed over (%d checked)" % len(used))
DEPSVARCHK

echo "=== [3/6] checking test scripts ==="
COUNT=$(ls -1 test-cases/scripts/script_*.sh | wc -l | tr -d ' ')
if [ "$COUNT" -gt 5 ]; then
    echo "  ERROR: $COUNT test scripts - the platform accepts at most 5"
    exit 1
fi
for f in test-cases/scripts/script_*.sh; do
    bash -n "$f"
    grep -q 'trap on_exit EXIT' "$f" || { echo "  $f lacks the single-verdict guarantee"; exit 1; }
    grep -q 'chown -R user:user' "$f" || { echo "  $f does not hand ownership back"; exit 1; }
    grep -q 'PYTHONDONTWRITEBYTECODE=1' "$f" || { echo "  $f may drop root-owned bytecode into the project"; exit 1; }
    for c in CURL_MAX SVC_WAIT JQ_MAX HARD_DEADLINE; do
        grep -q "${c}=" "$f" || { echo "  $f has no ${c} budget"; exit 1; }
    done
    if grep -qE '^\s*set -[eu]' "$f"; then
        echo "  $f uses set -e or set -u; a probe that fails must still reach a verdict"
        exit 1
    fi
done
# One apostrophe inside a <<'PY' body unbalances the surrounding $( ), and the
# syntax error surfaces on a line that looks fine.
python3 - <<'QUOTECHK'
import pathlib, sys

bad = []
for path in sorted(pathlib.Path("test-cases/scripts").glob("script_*.sh")):
    inside = False
    for number, line in enumerate(path.read_text().splitlines(), 1):
        if not inside and line.strip().endswith("<<'PY'"):
            inside = True
            continue
        if inside and line.strip() == "PY":
            inside = False
            continue
        if inside and "'" in line:
            bad.append("%s:%d: %s" % (path, number, line.strip()))
if bad:
    print("  ERROR: apostrophes inside a python heredoc body:")
    for line in bad:
        print("    " + line)
    sys.exit(1)
print("  no apostrophes inside any python heredoc body")
QUOTECHK
python3 - <<'PREAMBLECHK'
import pathlib, sys

def preamble(path):
    lines = pathlib.Path(path).read_text().splitlines()
    for index, line in enumerate(lines):
        if line.startswith("preflight() {"):
            return "\n".join(lines[2:index + 6])
    sys.exit("could not find the end of the preamble in %s" % path)

paths = sorted(pathlib.Path("test-cases/scripts").glob("script_*.sh"))
first = preamble(paths[0])
for path in paths[1:]:
    if preamble(path) != first:
        sys.exit("the shared preamble has drifted in %s - regenerate with ./gen_tests.sh"
                 % path)
print("  the shared preamble is identical across all %d scripts" % len(paths))
PREAMBLECHK
echo "  $COUNT test scripts syntax OK, each with a bounded time budget"

echo "=== [4/6] staging zips ==="
STAGE="$(mktemp -d)"
trap 'rm -rf "$STAGE"' EXIT
mkdir -p "$STAGE/setup/scripts" "$STAGE/setup/data" \
         "$STAGE/test/scripts"  "$STAGE/test/data"
cp setup/scripts/setup_script.sh "$STAGE/setup/scripts/"
cp test-cases/scripts/script_*.sh "$STAGE/test/scripts/"

mkdir -p dist
rm -f dist/Setup.zip dist/TestCase.zip
( cd "$STAGE/setup" && zip -qr "$DIR/dist/Setup.zip" scripts data )
( cd "$STAGE/test"  && zip -qr "$DIR/dist/TestCase.zip" scripts data )

echo "=== [5/6] verifying zip contents ==="
for z in dist/Setup.zip dist/TestCase.zip; do
    echo "-- $z"
    unzip -Z1 "$z" | sed 's/^/     /'
    grep -q '^scripts/$' <<< "$(unzip -Z1 "$z")" || { echo "ERROR: $z has no scripts/ folder"; exit 1; }
    grep -q '^data/$' <<< "$(unzip -Z1 "$z")"   || { echo "ERROR: $z has no data/ folder"; exit 1; }
done
if grep -qE 'common\.sh|run-all\.sh|\.DS_Store' <<< "$(unzip -Z1 dist/TestCase.zip)"; then
    echo "ERROR: TestCase.zip contains a non-test file"
    exit 1
fi

echo "=== [6/6] checking what the learner can see ==="
TABLE_LINES="$(grep -c '^|' problem-statement.md 2>/dev/null || true)"
if [ "${TABLE_LINES:-0}" -ne 0 ]; then
    echo "ERROR: problem-statement.md contains a markdown table (${TABLE_LINES} lines)"
    exit 1
fi
# Word boundaries matter: "the classify step" is not a reference to a class,
# and `class` on its own is a Python keyword.
TEACHY='\b(lecture|grading|grader|canary|sentinel|oracle|fixture)\b|\b(the|this|in) (class|course)\b'
if grep -rilE --include='*.py' --include='*.json' "$TEACHY" app/ >/dev/null 2>&1; then
    echo "ERROR: provided source under app/ reads like teaching material:"
    grep -rilE --include='*.py' --include='*.json' "$TEACHY" app/ | sed 's/^/       /'
    exit 1
fi
INTERNALS='\b(lecture|mock|deterministic|canary|sentinel|oracle|hardcode|hard-code)\b|__lw4t|grader-key|\b(the|this|in) (class|course)\b'
if grep -qiE "$INTERNALS" problem-statement.md; then
    echo "ERROR: problem-statement.md leaks an internal or reads like teaching material:"
    grep -niE "$INTERNALS" problem-statement.md | sed 's/^/       /'
    exit 1
fi
# The desk must never be readable under the learner project.
if grep -q 'chmod 700 "\$SVC"' setup/scripts/setup_script.sh; then
    echo "  the market site is installed root-only outside the learner project"
else
    echo "ERROR: the setup script does not lock down the site directory"
    exit 1
fi
if grep -rq 'marketsite' app/ 2>/dev/null; then
    echo "ERROR: the learner-visible source names the site implementation"
    exit 1
fi
echo "  provided sources and the statement are clean"
echo
echo "done. Max Score = ${COUNT} x 10"
