#!/bin/bash
# Regenerate setup/scripts/setup_script.sh from the template plus app/ and
# service/, verify every invariant this pack depends on, then stage
# dist/Setup.zip and dist/TestCase.zip from a clean directory.
set -euo pipefail

DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$DIR"

echo "=== [1/6] expanding setup template ==="
python3 - <<'PY'
import pathlib, re, sys

tpl = pathlib.Path("setup/setup_script.template.sh").read_text()

def expand(match):
    path = pathlib.Path(match.group(1))
    if not path.is_file():
        sys.exit("missing source file referenced by template: %s" % path)
    return path.read_text().rstrip("\n")

out, n = re.subn(r"@@FILE:([^@]+)@@", expand, tpl)
if "@@FILE:" in out:
    sys.exit("unexpanded marker left in generated setup script")
header = "# GENERATED by build.sh from setup/setup_script.template.sh - do not hand-edit.\n"
lines = out.split("\n")
out = lines[0] + "\n" + header + "\n".join(lines[1:])
pathlib.Path("setup/scripts/setup_script.sh").write_text(out)
print("  inlined %d source files" % n)
PY
chmod +x setup/scripts/setup_script.sh
bash -n setup/scripts/setup_script.sh
echo "  setup_script.sh syntax OK"

echo "=== [2/6] checking the pack against its own numbers ==="
python3 - <<'CONSISTCHK'
import hashlib, importlib.util, pathlib, sys

sys.path.insert(0, "service")
spec = importlib.util.spec_from_file_location("intakesvc", "service/intakesvc.py")
desk = importlib.util.module_from_spec(spec)
spec.loader.exec_module(desk)

statement = pathlib.Path("problem-statement.md").read_text()
gen = pathlib.Path("gen_tests.sh").read_text()

shipped = {d["name"]: d for d in desk.CORPUS.values() if d["group"] == "sample"}
graded = {d["name"]: d for d in desk.CORPUS.values() if d["group"] == "graded"}

# The graded set has to cover every flavor, or a pipeline that only ever sees
# one kind of document would pass.
def flavor(entry):
    if len(entry["text_pages"]) == entry["pages"]:
        return "digital"
    return "scanned" if not entry["text_pages"] else "mixed"

flavors = sorted({flavor(entry) for entry in graded.values()})
if flavors != ["digital", "mixed", "scanned"]:
    sys.exit("the graded set covers only %s" % ", ".join(flavors))
if len(graded) < 5:
    sys.exit("the graded set holds only %d documents" % len(graded))
print("  %d graded documents covering %s, %d shipped"
      % (len(graded), ", ".join(flavors), len(shipped)))

# Nothing the learner is given may also be graded.
overlap = set(shipped) & set(graded)
if overlap:
    sys.exit("these documents are both shipped and graded: %s" % sorted(overlap))
shipped_hashes = {h for h, e in desk.CORPUS.items() if e["group"] == "sample"}
graded_hashes = {h for h, e in desk.CORPUS.items() if e["group"] == "graded"}
if shipped_hashes & graded_hashes:
    sys.exit("a shipped document has the same bytes as a graded one")
print("  no document is both shipped and graded, by name or by content")

# The documents on disk have to be the ones the desk holds a plan for, or the
# project ships files the intake API will refuse.
for name, entry in sorted(shipped.items()):
    path = pathlib.Path("app/data/inbox") / name
    if not path.is_file():
        sys.exit("%s is in the plan but not in app/data/inbox" % name)
    digest = hashlib.sha256(path.read_bytes()).hexdigest()
    if desk.CORPUS.get(digest, {}).get("name") != name:
        sys.exit("app/data/inbox/%s does not match the plan the desk holds; "
                 "regenerate with tools/make_corpus.py" % name)
print("  the %d shipped documents match the plans byte for byte" % len(shipped))

# The cost table the statement quotes has to be the one the desk bills.
for strategy, cost in sorted(desk.COST_PER_PAGE.items()):
    if strategy not in statement:
        sys.exit("the statement never names the %s strategy" % strategy)
    if str(cost) not in statement:
        sys.exit("the statement does not quote the cost of %s (%d)"
                 % (strategy, cost))
print("  the three strategies and their per-page costs are all stated")

for name in ("classify", "layout_aware_chunks", "strategy_for",
             "intake/triage.py", "intake/chunk.py", "intake/worker.py",
             "ledger", "--inbox", "--once"):
    if name not in statement:
        sys.exit("the statement never names %s" % name)
print("  every graded name is fixed by the statement")
CONSISTCHK

echo "=== [3/6] checking test scripts ==="
COUNT=$(ls -1 test-cases/scripts/script_*.sh | wc -l | tr -d ' ')
if [ "$COUNT" -gt 5 ]; then
    echo "  ERROR: $COUNT test scripts - the platform accepts at most 5"
    exit 1
fi
for f in test-cases/scripts/script_*.sh; do
    bash -n "$f"
    grep -q 'trap on_exit EXIT' "$f" || { echo "  $f lacks the single-verdict guarantee"; exit 1; }
    grep -q 'chown -R user:user' "$f" || { echo "  $f does not hand ownership back"; exit 1; }
    grep -q 'PYTHONDONTWRITEBYTECODE=1' "$f" || { echo "  $f may drop root-owned bytecode into the project"; exit 1; }
    for c in CURL_MAX SVC_WAIT RUN_BUDGET HARD_DEADLINE; do
        grep -q "${c}=" "$f" || { echo "  $f has no ${c} budget"; exit 1; }
    done
    if grep -qE '^\s*set -[eu]' "$f"; then
        echo "  $f uses set -e or set -u; a probe that fails must still reach a verdict"
        exit 1
    fi
    # The platform helper installs an ERR trap. Inheriting it means a guard
    # returning 1 prints an internal error AFTER the verdict, the judge grades
    # the last line, and the submission is posted with no results at all.
    grep -qx 'trap - ERR' "$f" || { echo "  $f inherits the helper ERR trap"; exit 1; }
    grep -qx 'set +eE'    "$f" || { echo "  $f does not clear -e/-E after sourcing the helper"; exit 1; }
    grep -q '^exec 2>>'   "$f" || { echo "  $f leaves stderr on the judge stream"; exit 1; }
done
# The local helper has to be as hard to satisfy as the real one, or every
# harness here is measuring a fiction.
grep -q 'trap .handle_script_error' test-cases/scripts/common.sh \
    || { echo "  test-cases/scripts/common.sh is a convenience stub, not the replica"; exit 1; }
grep -q 'jq -n --arg status' test-cases/scripts/common.sh \
    || { echo "  test-cases/scripts/common.sh does not emit the JSON the judge parses"; exit 1; }
echo "  each check drops the inherited ERR trap, parks stderr, and is graded against the replica helper"
# One apostrophe inside a <<'PY' body unbalances the surrounding $( ), and the
# syntax error surfaces on a line that looks fine.
python3 - <<'QUOTECHK'
import pathlib, sys

bad = []
for path in sorted(pathlib.Path("test-cases/scripts").glob("script_*.sh")):
    inside = False
    for number, line in enumerate(path.read_text().splitlines(), 1):
        if not inside and line.strip().endswith("<<'PY'"):
            inside = True
            continue
        if inside and line.strip() == "PY":
            inside = False
            continue
        if inside and "'" in line:
            bad.append("%s:%d: %s" % (path, number, line.strip()))
if bad:
    print("  ERROR: apostrophes inside a python heredoc body:")
    for line in bad:
        print("    " + line)
    sys.exit(1)
print("  no apostrophes inside any python heredoc body")
QUOTECHK
python3 - <<'PREAMBLECHK'
import pathlib, sys

def preamble(path):
    lines = pathlib.Path(path).read_text().splitlines()
    for index, line in enumerate(lines):
        if line.startswith("preflight() {"):
            return "\n".join(lines[2:index + 7])
    sys.exit("could not find the end of the preamble in %s" % path)

paths = sorted(pathlib.Path("test-cases/scripts").glob("script_*.sh"))
first = preamble(paths[0])
for path in paths[1:]:
    if preamble(path) != first:
        sys.exit("the shared preamble has drifted in %s - regenerate with ./gen_tests.sh"
                 % path)
print("  the shared preamble is identical across all %d scripts" % len(paths))
PREAMBLECHK
echo "  $COUNT test scripts syntax OK, each with a bounded time budget"

echo "=== [3b/6] checking the VM can actually run this pack ==="
python3 - <<'VMCHK'
import pathlib, re, subprocess, sys, tempfile, time, urllib.request

setup = pathlib.Path("setup/scripts/setup_script.sh").read_text()

# 1. The project the setup script builds and the project the checks read have
#    to be the same directory. This shipped wrong once: the checks defaulted to
#    another lab's path and every one of them reported a missing project.
match = re.search(r'^PROJ="\$\{LAB_HOME\}/([^"]+)"', setup, re.M)
if not match:
    sys.exit("could not find PROJ in the setup script")
proj = "/home/user/" + match.group(1)
for path in sorted(pathlib.Path("test-cases/scripts").glob("script_*.sh")):
    found = re.search(r'^LAB_DIR="\$\{LAB_DIR:-([^}]+)\}"', path.read_text(), re.M)
    if not found:
        sys.exit("%s has no LAB_DIR default" % path)
    if found.group(1) != proj:
        sys.exit("%s reads %s but setup builds %s"
                 % (path, found.group(1), proj))
print("  setup builds %s and all 5 checks read it" % proj)

# 2. Every module the desk imports has to be written by the setup script, and
#    the pair has to start on its own. Shipping intakesvc.py without corpus.py
#    killed the desk on import, and every check then reported it unreachable.
for name in ("corpus.py", "intakesvc.py"):
    if 'cat > "${SVC}/%s"' % name not in setup:
        sys.exit("the setup script never writes ${SVC}/%s" % name)
print("  the setup script writes both desk modules")

# The helper prints its verdict with `jq -n`. If jq only arrives with the
# detached job, a learner who submits early gets an empty panel.
fg = setup.split("Grader tooling (detached")[0]
if "curl jq" not in fg:
    sys.exit("the setup script does not install jq in the foreground; the "
             "platform helper cannot print a verdict without it")
print("  jq is installed before provisioning returns")

# 3. systemd refuses a unit with no ExecStart, and a backslash-n inside the
#    heredoc silently produced exactly that.
unit = re.search(r"cat > /etc/systemd/system/[^\n]+<<UNIT\n(.*?)\nUNIT\n",
                 setup, re.S)
if not unit:
    sys.exit("could not find the desk unit in the setup script")
body = unit.group(1)
if "\\n" in body:
    sys.exit("the desk unit contains a literal backslash-n; systemd reads that "
             "as part of the previous value, not as a new directive")
if not re.search(r"^ExecStart=", body, re.M):
    sys.exit("the desk unit has no ExecStart line of its own")
print("  the desk unit has a real ExecStart on its own line")

# 4. Prove it: unpack the desk the way setup does, into a directory holding
#    nothing else, and ask it for its health.
stage = tempfile.mkdtemp()
for name in ("corpus.py", "intakesvc.py"):
    body = re.search(r'cat > "\$\{SVC\}/%s" <<.___ACFILE___.\n(.*?)\n___ACFILE___\n'
                     % re.escape(name), setup, re.S)
    if not body:
        sys.exit("could not lift %s back out of the setup script" % name)
    pathlib.Path(stage, name).write_text(body.group(1) + "\n")
port = "8791"
proc = subprocess.Popen([sys.executable, str(pathlib.Path(stage, "intakesvc.py"))],
                        cwd=stage, env={"ASHCOMBE_PORT": port, "PATH": "/usr/bin:/bin"},
                        stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
try:
    healthy = False
    for _ in range(30):
        try:
            urllib.request.urlopen("http://127.0.0.1:%s/health" % port, timeout=1).read()
            healthy = True
            break
        except Exception:
            if proc.poll() is not None:
                break
            time.sleep(0.5)
    if not healthy:
        proc.kill()
        sys.exit("the desk written by the setup script does not start:\n"
                 + (proc.stdout.read() or "")[-800:])
finally:
    proc.kill()
print("  the desk written by the setup script answers /health on its own")
VMCHK

echo "=== [4/6] staging zips ==="
STAGE="$(mktemp -d)"
trap 'rm -rf "$STAGE"' EXIT
mkdir -p "$STAGE/setup/scripts" "$STAGE/setup/data" \
         "$STAGE/test/scripts"  "$STAGE/test/data"
cp setup/scripts/setup_script.sh "$STAGE/setup/scripts/"
cp test-cases/scripts/script_*.sh "$STAGE/test/scripts/"

mkdir -p dist
rm -f dist/Setup.zip dist/TestCase.zip
( cd "$STAGE/setup" && zip -qr "$DIR/dist/Setup.zip" scripts data )
( cd "$STAGE/test"  && zip -qr "$DIR/dist/TestCase.zip" scripts data )

echo "=== [5/6] verifying zip contents ==="
# The listing is captured before it is searched: `grep -q` closes the pipe on
# its first match, unzip takes SIGPIPE, and under pipefail that reads as a
# missing folder about half the time.
for z in dist/Setup.zip dist/TestCase.zip; do
    echo "-- $z"
    LISTING="$(unzip -Z1 "$z")"
    printf '%s\n' "$LISTING" | sed 's/^/     /'
    printf '%s\n' "$LISTING" | grep -q '^scripts/$' || { echo "ERROR: $z has no scripts/ folder"; exit 1; }
    printf '%s\n' "$LISTING" | grep -q '^data/$'    || { echo "ERROR: $z has no data/ folder"; exit 1; }
done
LISTING="$(unzip -Z1 dist/TestCase.zip)"
if printf '%s\n' "$LISTING" | grep -qE 'common\.sh|run-all\.sh|\.DS_Store'; then
    echo "ERROR: TestCase.zip contains a non-test file"
    exit 1
fi

echo "=== [6/6] checking what the learner can see ==="
TABLE_LINES="$(grep -c '^|' problem-statement.md 2>/dev/null || true)"
if [ "${TABLE_LINES:-0}" -ne 0 ]; then
    echo "ERROR: problem-statement.md contains a markdown table (${TABLE_LINES} lines)"
    exit 1
fi
# Word boundaries matter: "the classify step" is not a reference to a class,
# and `class` on its own is a Python keyword.
TEACHY='\b(lecture|grading|grader|canary|sentinel|oracle|fixture)\b|\b(the|this|in) (class|course)\b'
if grep -rilE --include='*.py' --include='*.json' "$TEACHY" app/ >/dev/null 2>&1; then
    echo "ERROR: provided source under app/ reads like teaching material:"
    grep -rilE --include='*.py' --include='*.json' "$TEACHY" app/ | sed 's/^/       /'
    exit 1
fi
INTERNALS='\b(lecture|mock|deterministic|canary|sentinel|oracle|hardcode|hard-code)\b|__ac5t|grader-key|\b(the|this|in) (class|course)\b'
if grep -qiE "$INTERNALS" problem-statement.md; then
    echo "ERROR: problem-statement.md leaks an internal or reads like teaching material:"
    grep -niE "$INTERNALS" problem-statement.md | sed 's/^/       /'
    exit 1
fi
if grep -q 'chmod 700 "\$SVC"' setup/scripts/setup_script.sh; then
    echo "  the support desk is installed root-only outside the learner project"
else
    echo "ERROR: the setup script does not lock down the desk directory"
    exit 1
fi
if grep -rq 'intakesvc\|corpus.py' app/ 2>/dev/null; then
    echo "ERROR: the learner-visible source names the desk implementation"
    exit 1
fi
echo "  provided sources and the statement are clean"
echo
echo "done. Max Score = ${COUNT} x 10"
