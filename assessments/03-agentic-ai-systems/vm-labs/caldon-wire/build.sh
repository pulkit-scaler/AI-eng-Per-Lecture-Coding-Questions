#!/bin/bash
# Regenerate setup/scripts/setup_script.sh from the template plus app/ and
# service/, then stage dist/Setup.zip and dist/TestCase.zip from a clean
# directory so no stub or harness can leak into the test pack.
#
# Both zips carry a scripts/ AND a data/ folder at the root; the platform
# rejects the older scripts-only shape.
set -euo pipefail

DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$DIR"

echo "=== [1/6] expanding setup template ==="
python3 - <<'PY'
import pathlib, re, sys

tpl = pathlib.Path("setup/setup_script.template.sh").read_text()

def expand(match):
    path = pathlib.Path(match.group(1))
    if not path.is_file():
        sys.exit("missing source file referenced by template: %s" % path)
    return path.read_text().rstrip("\n")

out, n = re.subn(r"@@FILE:([^@]+)@@", expand, tpl)
if "@@FILE:" in out:
    sys.exit("unexpanded marker left in generated setup script")
header = "# GENERATED by build.sh from setup/setup_script.template.sh - do not hand-edit.\n"
lines = out.split("\n")
out = lines[0] + "\n" + header + "\n".join(lines[1:])
pathlib.Path("setup/scripts/setup_script.sh").write_text(out)
print("  inlined %d source files" % n)
PY
chmod +x setup/scripts/setup_script.sh
bash -n setup/scripts/setup_script.sh
echo "  setup_script.sh syntax OK"

echo "=== [2/6] checking the provided kit against the wire desk ==="
python3 - <<'CONSISTCHK'
import json, pathlib, re, sys

prompts = pathlib.Path("app/wire_kit/prompts.py").read_text()
service = pathlib.Path("service/wired.py").read_text()

# Every marker the desk dispatches on has to appear in the prompts the learner
# is handed, or a whole task falls through to the default reply and no amount
# of correct async code can pass it.
markers = re.findall(r'\("(?:summary|urgency|note|bulletin)",\s*"([^"]+)"\)',
                     service)
if len(markers) != 4:
    sys.exit("expected 4 dispatch markers in service/wired.py, found %d"
             % len(markers))
lowered = prompts.lower()
for marker in markers:
    if marker.lower() not in lowered:
        sys.exit("dispatch marker %r is not present in app/wire_kit/prompts.py"
                 % marker)
print("  all %d dispatch markers present in the provided prompts" % len(markers))

# The desks the statement names and the desks the endpoint staffs must be the
# same list, or a learner loses points to a disagreement between two files.
left = re.search(r"DESKS = \[([^\]]*)\]", prompts)
right = re.search(r"STAFFED_DESKS = \[([^\]]*)\]", service)
if not left or not right:
    sys.exit("could not read the desk list from both files")
if sorted(re.findall(r'"([^"]+)"', left.group(1))) != \
   sorted(re.findall(r'"([^"]+)"', right.group(1))):
    sys.exit("the desk list differs between the toolkit and the wire desk")
print("  the desk lists agree between the toolkit and the wire desk")

# The feed is written to two places by setup; both come from this one file, so
# the only thing to verify is that it is valid and that every graded story is
# in it.
feed = json.loads(pathlib.Path("app/data/wire_feed.json").read_text())
ids = {s["id"] for s in feed["stories"]}
gen = pathlib.Path("gen_tests.sh").read_text()
graded = set(re.findall(r"wf-\d+", gen))
missing = graded - ids
if missing:
    sys.exit("gen_tests.sh grades stories that are not on the wire: %s"
             % sorted(missing))
print("  all %d graded stories are present in the feed of %d"
      % (len(graded), len(ids)))

# A story used as a worked example must not also be a graded input, or a
# learner who hardcodes what they saw in the statement scores for it.
statement = pathlib.Path("problem-statement.md").read_text()
local = pathlib.Path("app/check_local.py").read_text()
shown = set(re.findall(r"wf-\d+", statement)) | set(re.findall(r"wf-\d+", local))
overlap = shown & graded
if overlap:
    sys.exit("these stories are both shown to the learner and graded: %s"
             % sorted(overlap))
print("  no graded story appears in the statement or in check_local.py")
CONSISTCHK

echo "=== [3/6] checking test scripts ==="
COUNT=$(ls -1 test-cases/scripts/script_*.sh | wc -l | tr -d ' ')
if [ "$COUNT" -gt 5 ]; then
    echo "  ERROR: $COUNT test scripts - the platform accepts at most 5"
    exit 1
fi
for f in test-cases/scripts/script_*.sh; do
    bash -n "$f"
    c=$(grep -c 'report "' "$f")
    [ "$c" -ge 2 ] || { echo "  $f has no verdict calls"; exit 1; }
    grep -q 'trap on_exit EXIT' "$f" || { echo "  $f lacks the single-verdict guarantee"; exit 1; }
    grep -q 'chown -R user:user' "$f" || { echo "  $f does not hand ownership back"; exit 1; }
    # Every wait a check performs must be bounded, or the portal kills it as a
    # blocking process instead of scoring it.
    grep -q 'RUN_BUDGET=' "$f" || { echo "  $f has no learner-run time budget"; exit 1; }
    grep -q 'SVC_WAIT=' "$f"   || { echo "  $f has no wire desk wait budget"; exit 1; }
    grep -q 'CURL_MAX=' "$f"   || { echo "  $f has no per-call budget"; exit 1; }
    grep -q 'DEPS_WAIT=' "$f"  || { echo "  $f has no dependency-wait budget"; exit 1; }
    grep -q 'PYTHONDONTWRITEBYTECODE=1' "$f" || { echo "  $f may drop root-owned bytecode into the project"; exit 1; }
    if grep -qE '^\s*set -[eu]' "$f"; then
        echo "  $f uses set -e or set -u; a probe that fails must still reach a verdict"
        exit 1
    fi
done
# A single apostrophe inside a <<'PY' ... PY body unbalances the surrounding
# $( ) command substitution, and the resulting syntax error surfaces on a line
# that looks fine. Enforced here because it is invisible on inspection.
python3 - <<'QUOTECHK'
import pathlib, sys

bad = []
for path in sorted(pathlib.Path("test-cases/scripts").glob("script_*.sh")):
    inside = False
    for number, line in enumerate(path.read_text().splitlines(), 1):
        if not inside and line.strip().endswith("<<'PY'"):
            inside = True
            continue
        if inside and line.strip() == "PY":
            inside = False
            continue
        if inside and "'" in line:
            bad.append("%s:%d: %s" % (path, number, line.strip()))
if bad:
    print("  ERROR: apostrophes inside a python heredoc body:")
    for line in bad:
        print("    " + line)
    sys.exit(1)
print("  no apostrophes inside any python heredoc body")
QUOTECHK
# The preamble is duplicated into every script on purpose, so drift between two
# of them is a real hazard rather than a style question.
python3 - <<'PREAMBLECHK'
import pathlib, sys

def preamble(path):
    lines = pathlib.Path(path).read_text().splitlines()
    for index, line in enumerate(lines):
        if line.startswith("preflight() {"):
            return "\n".join(lines[2:index + 6])
    sys.exit("could not find the end of the preamble in %s" % path)

paths = sorted(pathlib.Path("test-cases/scripts").glob("script_*.sh"))
first = preamble(paths[0])
for path in paths[1:]:
    if preamble(path) != first:
        sys.exit("the shared preamble has drifted in %s - regenerate with ./gen_tests.sh"
                 % path)
print("  the shared preamble is identical across all %d scripts" % len(paths))
PREAMBLECHK
echo "  $COUNT test scripts syntax OK, each with a bounded time budget"

echo "=== [4/6] staging zips ==="
STAGE="$(mktemp -d)"
trap 'rm -rf "$STAGE"' EXIT
mkdir -p "$STAGE/setup/scripts" "$STAGE/setup/data" \
         "$STAGE/test/scripts"  "$STAGE/test/data"
cp setup/scripts/setup_script.sh "$STAGE/setup/scripts/"
cp test-cases/scripts/script_*.sh "$STAGE/test/scripts/"

mkdir -p dist
rm -f dist/Setup.zip dist/TestCase.zip
( cd "$STAGE/setup" && zip -qr "$DIR/dist/Setup.zip" scripts data )
( cd "$STAGE/test"  && zip -qr "$DIR/dist/TestCase.zip" scripts data )

echo "=== [5/6] verifying zip contents ==="
echo "-- Setup.zip"
unzip -Z1 dist/Setup.zip | sed 's/^/     /'
echo "-- TestCase.zip"
unzip -Z1 dist/TestCase.zip | sed 's/^/     /'
for z in dist/Setup.zip dist/TestCase.zip; do
    grep -q '^scripts/$' <<< "$(unzip -Z1 "$z")" || { echo "ERROR: $z has no scripts/ folder"; exit 1; }
    grep -q '^data/$' <<< "$(unzip -Z1 "$z")"   || { echo "ERROR: $z has no data/ folder"; exit 1; }
done
if grep -qE 'common\.sh|run-all\.sh|\.DS_Store' <<< "$(unzip -Z1 dist/TestCase.zip)"; then
    echo "ERROR: TestCase.zip contains a non-test file"
    exit 1
fi

echo "=== [6/6] checking what the learner can see ==="
# The learner-facing statement is rendered by a viewer with no GFM table
# support, so a table collapses into a wall of pipe characters on their screen.
TABLE_LINES="$(grep -c '^|' problem-statement.md 2>/dev/null || true)"
if [ "${TABLE_LINES:-0}" -ne 0 ]; then
    echo "ERROR: problem-statement.md contains a markdown table (${TABLE_LINES} lines)"
    exit 1
fi
# Nothing under app/ is allowed to describe how the lab is graded or hint that
# the wire desk is anything other than the service it appears to be.
for word in lecture course "class " grading grader mock canary sentinel oracle stub; do
    if grep -ril --include='*.py' -- "$word" app/ >/dev/null 2>&1; then
        echo "ERROR: provided source under app/ mentions '$word'"
        grep -ril --include='*.py' -- "$word" app/ | sed 's/^/       /'
        exit 1
    fi
done
# Same for the statement, which additionally must not explain the anti-cheat
# design or name the internals the checks read.
for word in mock deterministic canary sentinel oracle "hard-code" hardcode "__cw"; do
    if grep -qi -- "$word" problem-statement.md; then
        echo "ERROR: problem-statement.md mentions '$word'"
        exit 1
    fi
done
echo "  provided sources and the statement are clean"
echo
echo "done. Max Score = ${COUNT} x 10"
