#!/bin/bash
# Regenerate setup/scripts/setup_script.sh from the template plus app/ and
# service/, verify every invariant this pack depends on, then stage
# dist/Setup.zip and dist/TestCase.zip from a clean directory.
set -euo pipefail

DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$DIR"

echo "=== [1/6] expanding setup template ==="
python3 - <<'PY'
import pathlib, re, sys

tpl = pathlib.Path("setup/setup_script.template.sh").read_text()

def expand(match):
    path = pathlib.Path(match.group(1))
    if not path.is_file():
        sys.exit("missing source file referenced by template: %s" % path)
    return path.read_text().rstrip("\n")

out, n = re.subn(r"@@FILE:([^@]+)@@", expand, tpl)
if "@@FILE:" in out:
    sys.exit("unexpanded marker left in generated setup script")
header = "# GENERATED by build.sh from setup/setup_script.template.sh - do not hand-edit.\n"
lines = out.split("\n")
out = lines[0] + "\n" + header + "\n".join(lines[1:])
pathlib.Path("setup/scripts/setup_script.sh").write_text(out)
print("  inlined %d source files" % n)
PY
chmod +x setup/scripts/setup_script.sh
bash -n setup/scripts/setup_script.sh
echo "  setup_script.sh syntax OK"

echo "=== [2/6] checking the pack against its own numbers ==="
python3 - <<'CONSISTCHK'
import importlib.util, json, pathlib, re, sys

service = pathlib.Path("service/judgesvc.py").read_text()
gen = pathlib.Path("gen_tests.sh").read_text()
statement = pathlib.Path("problem-statement.md").read_text()
sample = json.loads(pathlib.Path("app/data/pool_sample.json").read_text())["pool"]

# The two graders have to disagree somewhere, or the escalation theme grades
# nothing, and each has to use both labels, or kappa is undefined on the pool
# the gate runs over.
spec = importlib.util.spec_from_file_location("judgesvc", "service/judgesvc.py")
desk = importlib.util.module_from_spec(spec)
spec.loader.exec_module(desk)

families = sorted(desk.VERDICTS)
if len(families) < 2:
    sys.exit("the desk offers %d grading families" % len(families))
first, second = (desk.VERDICTS[f] for f in families[:2])
graded_ids = {item["id"] for item in desk.POOL}
common = sorted((set(first) & set(second)) & graded_ids)
disagreements = [i for i in common if first[i][0] != second[i][0]]
if len(disagreements) != 1:
    sys.exit("the two graders disagree on %d items; the checks expect exactly "
             "one" % len(disagreements))
for family in families[:2]:
    labels = {desk.VERDICTS[family][i][0] for i in common}
    if len(labels) < 2:
        sys.exit("the %s family used a single label over the pool, so kappa "
                 "would be undefined on the graded run" % family)
if not desk.NO_JSON:
    sys.exit("no grading reply is served without JSON in it")
print("  %d grading families, %d pool items, disagreeing on exactly %s"
      % (len(families), len(common), disagreements[0]))
print("  %d grading reply arrives with no JSON in it" % len(desk.NO_JSON))

# The item the checks name has to be the one they disagree on.
if disagreements[0] not in gen:
    sys.exit("the checks never name the disagreement item %s" % disagreements[0])

# Nothing the learner is shown may also be graded.
shown = {r["problem"] for r in sample}
graded = {item["problem"] for item in desk.POOL}
overlap = shown & graded
if overlap:
    sys.exit("these problems are both shipped and graded: %s" % sorted(overlap)[:2])
print("  %d shipped problems, %d graded problems, no overlap"
      % (len(shown), len(graded)))

# Everything the interface contract promises has to be in the statement.
for name in ("build_golden", "exact_match", "symbolic_match",
             "build_judge_prompt", "parse_judge_response", "judge_prediction",
             "observed_agreement", "cohen_kappa", "ensemble", "gate.py"):
    if name not in statement:
        sys.exit("the statement never names %s" % name)
for key in ("correct", "reasoning_quality", "used_tool_appropriately",
            "explanation"):
    if key not in statement:
        sys.exit("the statement does not state the %s rubric field" % key)
print("  every graded name and rubric field is stated")
CONSISTCHK

echo "=== [3/6] checking test scripts ==="
COUNT=$(ls -1 test-cases/scripts/script_*.sh | wc -l | tr -d ' ')
if [ "$COUNT" -gt 5 ]; then
    echo "  ERROR: $COUNT test scripts - the platform accepts at most 5"
    exit 1
fi
for f in test-cases/scripts/script_*.sh; do
    bash -n "$f"
    grep -q 'trap on_exit EXIT' "$f" || { echo "  $f lacks the single-verdict guarantee"; exit 1; }
    grep -q 'chown -R user:user' "$f" || { echo "  $f does not hand ownership back"; exit 1; }
    grep -q 'PYTHONDONTWRITEBYTECODE=1' "$f" || { echo "  $f may drop root-owned bytecode into the project"; exit 1; }
    for c in CURL_MAX SVC_WAIT RUN_BUDGET HARD_DEADLINE; do
        grep -q "${c}=" "$f" || { echo "  $f has no ${c} budget"; exit 1; }
    done
    if grep -qE '^\s*set -[eu]' "$f"; then
        echo "  $f uses set -e or set -u; a probe that fails must still reach a verdict"
        exit 1
    fi
    # The platform helper installs an ERR trap. Inheriting it means a guard
    # returning 1 prints an internal error AFTER the verdict, the judge grades
    # the last line, and the submission is posted with no results at all.
    grep -qx 'trap - ERR' "$f" || { echo "  $f inherits the helper ERR trap"; exit 1; }
    grep -qx 'set +eE'    "$f" || { echo "  $f does not clear -e/-E after sourcing the helper"; exit 1; }
    grep -q '^exec 2>>'   "$f" || { echo "  $f leaves stderr on the judge stream"; exit 1; }
done
# The local helper has to be as hard to satisfy as the real one, or every
# harness here is measuring a fiction.
grep -q 'trap .handle_script_error' test-cases/scripts/common.sh \
    || { echo "  test-cases/scripts/common.sh is a convenience stub, not the replica"; exit 1; }
grep -q 'jq -n --arg status' test-cases/scripts/common.sh \
    || { echo "  test-cases/scripts/common.sh does not emit the JSON the judge parses"; exit 1; }
# The helper prints its verdict with `jq -n`. If jq only arrives with the
# detached job, a learner who submits early gets an empty panel.
python3 - <<'JQCHK'
import pathlib, sys
setup = pathlib.Path("setup/scripts/setup_script.sh").read_text()
if "curl jq" not in setup.split("Grader tooling (detached")[0]:
    sys.exit("  the setup script does not install jq in the foreground; the "
             "platform helper cannot print a verdict without it")
JQCHK
echo "  each check drops the inherited ERR trap, parks stderr, is graded against the replica helper, and jq lands before provisioning returns"
# One apostrophe inside a <<'PY' body unbalances the surrounding $( ), and the
# syntax error surfaces on a line that looks fine.
python3 - <<'QUOTECHK'
import pathlib, sys

bad = []
for path in sorted(pathlib.Path("test-cases/scripts").glob("script_*.sh")):
    inside = False
    for number, line in enumerate(path.read_text().splitlines(), 1):
        if not inside and line.strip().endswith("<<'PY'"):
            inside = True
            continue
        if inside and line.strip() == "PY":
            inside = False
            continue
        if inside and "'" in line:
            bad.append("%s:%d: %s" % (path, number, line.strip()))
if bad:
    print("  ERROR: apostrophes inside a python heredoc body:")
    for line in bad:
        print("    " + line)
    sys.exit(1)
print("  no apostrophes inside any python heredoc body")
QUOTECHK
python3 - <<'PREAMBLECHK'
import pathlib, sys

def preamble(path):
    lines = pathlib.Path(path).read_text().splitlines()
    for index, line in enumerate(lines):
        if line.startswith("preflight() {"):
            return "\n".join(lines[2:index + 7])
    sys.exit("could not find the end of the preamble in %s" % path)

paths = sorted(pathlib.Path("test-cases/scripts").glob("script_*.sh"))
first = preamble(paths[0])
for path in paths[1:]:
    if preamble(path) != first:
        sys.exit("the shared preamble has drifted in %s - regenerate with ./gen_tests.sh"
                 % path)
print("  the shared preamble is identical across all %d scripts" % len(paths))
PREAMBLECHK
echo "  $COUNT test scripts syntax OK, each with a bounded time budget"

echo "=== [4/6] staging zips ==="
STAGE="$(mktemp -d)"
trap 'rm -rf "$STAGE"' EXIT
mkdir -p "$STAGE/setup/scripts" "$STAGE/setup/data" \
         "$STAGE/test/scripts"  "$STAGE/test/data"
cp setup/scripts/setup_script.sh "$STAGE/setup/scripts/"
cp test-cases/scripts/script_*.sh "$STAGE/test/scripts/"

mkdir -p dist
rm -f dist/Setup.zip dist/TestCase.zip
( cd "$STAGE/setup" && zip -qr "$DIR/dist/Setup.zip" scripts data )
( cd "$STAGE/test"  && zip -qr "$DIR/dist/TestCase.zip" scripts data )

echo "=== [5/6] verifying zip contents ==="
# The listing is captured before it is searched: `grep -q` closes the pipe on
# its first match, unzip takes SIGPIPE, and under pipefail that reads as a
# missing folder about half the time.
for z in dist/Setup.zip dist/TestCase.zip; do
    echo "-- $z"
    LISTING="$(unzip -Z1 "$z")"
    printf '%s\n' "$LISTING" | sed 's/^/     /'
    printf '%s\n' "$LISTING" | grep -q '^scripts/$' || { echo "ERROR: $z has no scripts/ folder"; exit 1; }
    printf '%s\n' "$LISTING" | grep -q '^data/$'    || { echo "ERROR: $z has no data/ folder"; exit 1; }
done
LISTING="$(unzip -Z1 dist/TestCase.zip)"
if printf '%s\n' "$LISTING" | grep -qE 'common\.sh|run-all\.sh|\.DS_Store'; then
    echo "ERROR: TestCase.zip contains a non-test file"
    exit 1
fi

echo "=== [6/6] checking what the learner can see ==="
TABLE_LINES="$(grep -c '^|' problem-statement.md 2>/dev/null || true)"
if [ "${TABLE_LINES:-0}" -ne 0 ]; then
    echo "ERROR: problem-statement.md contains a markdown table (${TABLE_LINES} lines)"
    exit 1
fi
# Word boundaries matter: "the classify step" is not a reference to a class,
# and `class` on its own is a Python keyword.
# "grading" and "grader" are this lab's subject matter, not leaked internals,
# so they are not in the list here the way they are in the other packs.
TEACHY='\b(lecture|canary|sentinel|oracle|fixture)\b|\b(the|this|in) (class|course)\b'
if grep -rilE --include='*.py' --include='*.json' "$TEACHY" app/ >/dev/null 2>&1; then
    echo "ERROR: provided source under app/ reads like teaching material:"
    grep -rilE --include='*.py' --include='*.json' "$TEACHY" app/ | sed 's/^/       /'
    exit 1
fi
INTERNALS='\b(lecture|mock|deterministic|canary|sentinel|oracle|hardcode|hard-code)\b|__bh4r|grader-key|\b(the|this|in) (class|course)\b'
if grep -qiE "$INTERNALS" problem-statement.md; then
    echo "ERROR: problem-statement.md leaks an internal or reads like teaching material:"
    grep -niE "$INTERNALS" problem-statement.md | sed 's/^/       /'
    exit 1
fi
if grep -q 'chmod 700 "\$SVC"' setup/scripts/setup_script.sh; then
    echo "  the support desk is installed root-only outside the learner project"
else
    echo "ERROR: the setup script does not lock down the desk directory"
    exit 1
fi
if grep -rq 'judgesvc' app/ 2>/dev/null; then
    echo "ERROR: the learner-visible source names the desk implementation"
    exit 1
fi
echo "  provided sources and the statement are clean"
echo
echo "done. Max Score = ${COUNT} x 10"
