#!/bin/bash
# Regenerate setup/scripts/setup_script.sh from the template plus app/ and
# service/, verify every invariant this pack depends on, then stage
# dist/Setup.zip and dist/TestCase.zip from a clean directory.
#
# Both zips carry a scripts/ AND a data/ folder at the root; the platform
# rejects the older scripts-only shape.
set -euo pipefail

DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$DIR"

echo "=== [1/6] expanding setup template ==="
python3 - <<'PY'
import pathlib, re, sys

tpl = pathlib.Path("setup/setup_script.template.sh").read_text()

def expand(match):
    path = pathlib.Path(match.group(1))
    if not path.is_file():
        sys.exit("missing source file referenced by template: %s" % path)
    return path.read_text().rstrip("\n")

out, n = re.subn(r"@@FILE:([^@]+)@@", expand, tpl)
if "@@FILE:" in out:
    sys.exit("unexpanded marker left in generated setup script")
header = "# GENERATED by build.sh from setup/setup_script.template.sh - do not hand-edit.\n"
lines = out.split("\n")
out = lines[0] + "\n" + header + "\n".join(lines[1:])
pathlib.Path("setup/scripts/setup_script.sh").write_text(out)
print("  inlined %d source files" % n)
PY
chmod +x setup/scripts/setup_script.sh
bash -n setup/scripts/setup_script.sh
echo "  setup_script.sh syntax OK"

echo "=== [2/6] checking the pack against its own numbers ==="
python3 - <<'CONSISTCHK'
import importlib.util, json, pathlib, re, sys

def load(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module

prompts = load("prompts", "app/news_kit/prompts.py")
queue = json.loads(
    pathlib.Path("app/data/assignments.json").read_text())["assignments"]
visible = {a["assignment"] for a in queue}

service = pathlib.Path("service/wired.py").read_text()
gen = pathlib.Path("gen_tests.sh").read_text()
statement = pathlib.Path("problem-statement.md").read_text()

# Every assignment the wire can answer has to be one the learner can see, and
# every visible assignment needs an answer - either gap is a lab where a correct
# service cannot pass.
answered = set(re.findall(r'"(OR-\d{4})": \{', service))
if answered != visible:
    sys.exit("the wire and the assignment queue disagree: %s"
             % sorted(answered ^ visible))
print("  %d assignments, each with an answer on the wire" % len(visible))

# Exactly three sub-questions per assignment, because the desk order maps one
# desk to each index and a fourth would silently never be researched.
for match in re.finditer(r'"(OR-\d{4})": \{\s*"angle".*?"sub_questions": \[(.*?)\]',
                          service, re.S):
    count = len(re.findall(r'"[^"]{10,}"', match.group(2)))
    if count != 3:
        sys.exit("%s has %d sub-questions, and the desk order has %d desks"
                 % (match.group(1), count, len(prompts.DESK_ORDER)))
print("  every assignment has exactly %d sub-questions, one per desk"
      % len(prompts.DESK_ORDER))

# The wire and the kit must agree on the desks and their order, or a finding is
# attributed to the wrong desk.
wire_desks = re.search(r'^DESKS = \((.*?)\)$', service, re.M)
if not wire_desks:
    sys.exit("could not read the desk list from the wire")
if tuple(re.findall(r'"([^"]+)"', wire_desks.group(1))) != tuple(prompts.DESK_ORDER):
    sys.exit("the wire desk order and DESK_ORDER differ")
print("  the wire and the kit agree on the desk order")

# The limit the statement quotes has to be the limit the kit exports.
if "MAX_REVISIONS" not in statement or str(prompts.MAX_REVISIONS) not in statement:
    sys.exit("the statement does not name and value MAX_REVISIONS")
print("  MAX_REVISIONS is named and valued in the statement")

# The accounting check compares the wire trace against one expected figure per
# role. On an assignment with a barred source the researcher count is a design
# choice and not a rule - a service may read the record and drop it, or notice
# the flag on the desk answer and never ask - so that check has to stay on
# assignments where every desk answers and nothing is barred.
tc05 = pathlib.Path("test-cases/scripts/script_05.sh").read_text()
accounted = set()
for block in re.findall(r"for a in ((?:OR-\d{4}\s*)+); do", tc05):
    accounted |= set(re.findall(r"OR-\d{4}", block))
if not accounted:
    sys.exit("could not read which assignments the accounting check grades")
rows = dict((a, (d.strip(), b.strip())) for a, d, b in re.findall(
    r'"(OR-\d{4})": \{.*?"down": ([^,]+), "blocked": ([^}]+)\}', service, re.S))
for name in sorted(accounted):
    if name not in rows:
        sys.exit("the accounting check grades %s, which the wire cannot answer"
                 % name)
    down, blocked = rows[name]
    if down != "None" or blocked != "None":
        sys.exit("the accounting check grades %s, which has down=%s blocked=%s "
                 "- the researcher count there is not decided by the rules"
                 % (name, down, blocked))
print("  the accounting check grades %d assignments, none with a desk down or "
      "a source barred" % len(accounted))

# An assignment used as a worked example must not also be graded.
graded = set(re.findall(r'"(OR-\d{4})"', gen)) | set(re.findall(r'\bOR-\d{4}\b', gen))
shown = set(re.findall(r'\bOR-\d{4}\b', statement)) \
    | set(re.findall(r'\bOR-\d{4}\b',
                     pathlib.Path("app/check_local.py").read_text()))
overlap = graded & shown
if overlap:
    sys.exit("these assignments are both shown to the learner and graded: %s"
             % sorted(overlap))
missing = graded - visible
if missing:
    sys.exit("the checks grade assignments that are not on the queue: %s"
             % sorted(missing))
print("  %d graded assignments, none of them shown to the learner"
      % len(graded))
CONSISTCHK

echo "=== [3/6] checking test scripts ==="
COUNT=$(ls -1 test-cases/scripts/script_*.sh | wc -l | tr -d ' ')
if [ "$COUNT" -gt 5 ]; then
    echo "  ERROR: $COUNT test scripts - the platform accepts at most 5"
    exit 1
fi
for f in test-cases/scripts/script_*.sh; do
    bash -n "$f"
    grep -q 'trap on_exit EXIT' "$f" || { echo "  $f lacks the single-verdict guarantee"; exit 1; }
    grep -q 'chown -R user:user' "$f" || { echo "  $f does not hand ownership back"; exit 1; }
    grep -q 'PYTHONDONTWRITEBYTECODE=1' "$f" || { echo "  $f may drop root-owned bytecode into the project"; exit 1; }
    for c in CURL_MAX WIRE_WAIT SVC_WAIT DEPS_WAIT BRIEF_BUDGET HARD_DEADLINE; do
        grep -q "${c}=" "$f" || { echo "  $f has no ${c} budget"; exit 1; }
    done
    if grep -qE '^\s*set -[eu]' "$f"; then
        echo "  $f uses set -e or set -u; a probe that fails must still reach a verdict"
        exit 1
    fi
done
# One apostrophe inside a <<'PY' body unbalances the surrounding $( ), and the
# syntax error surfaces on a line that looks fine.
python3 - <<'QUOTECHK'
import pathlib, sys

bad = []
for path in sorted(pathlib.Path("test-cases/scripts").glob("script_*.sh")):
    inside = False
    for number, line in enumerate(path.read_text().splitlines(), 1):
        if not inside and line.strip().endswith("<<'PY'"):
            inside = True
            continue
        if inside and line.strip() == "PY":
            inside = False
            continue
        if inside and "'" in line:
            bad.append("%s:%d: %s" % (path, number, line.strip()))
if bad:
    print("  ERROR: apostrophes inside a python heredoc body:")
    for line in bad:
        print("    " + line)
    sys.exit(1)
print("  no apostrophes inside any python heredoc body")
QUOTECHK
python3 - <<'PREAMBLECHK'
import pathlib, sys

def preamble(path):
    lines = pathlib.Path(path).read_text().splitlines()
    for index, line in enumerate(lines):
        if line.startswith("same_list() {"):
            return "\n".join(lines[2:index + 4])
    sys.exit("could not find the end of the preamble in %s" % path)

paths = sorted(pathlib.Path("test-cases/scripts").glob("script_*.sh"))
first = preamble(paths[0])
for path in paths[1:]:
    if preamble(path) != first:
        sys.exit("the shared preamble has drifted in %s - regenerate with ./gen_tests.sh"
                 % path)
print("  the shared preamble is identical across all %d scripts" % len(paths))
PREAMBLECHK
echo "  $COUNT test scripts syntax OK, each with a bounded time budget"

echo "=== [4/6] staging zips ==="
STAGE="$(mktemp -d)"
trap 'rm -rf "$STAGE"' EXIT
mkdir -p "$STAGE/setup/scripts" "$STAGE/setup/data" \
         "$STAGE/test/scripts"  "$STAGE/test/data"
cp setup/scripts/setup_script.sh "$STAGE/setup/scripts/"
cp test-cases/scripts/script_*.sh "$STAGE/test/scripts/"

mkdir -p dist
rm -f dist/Setup.zip dist/TestCase.zip
( cd "$STAGE/setup" && zip -qr "$DIR/dist/Setup.zip" scripts data )
( cd "$STAGE/test"  && zip -qr "$DIR/dist/TestCase.zip" scripts data )

echo "=== [5/6] verifying zip contents ==="
for z in dist/Setup.zip dist/TestCase.zip; do
    echo "-- $z"
    unzip -Z1 "$z" | sed 's/^/     /'
    grep -q '^scripts/$' <<< "$(unzip -Z1 "$z")" || { echo "ERROR: $z has no scripts/ folder"; exit 1; }
    grep -q '^data/$' <<< "$(unzip -Z1 "$z")"   || { echo "ERROR: $z has no data/ folder"; exit 1; }
done
if grep -qE 'common\.sh|run-all\.sh|\.DS_Store' <<< "$(unzip -Z1 dist/TestCase.zip)"; then
    echo "ERROR: TestCase.zip contains a non-test file"
    exit 1
fi

echo "=== [6/6] checking what the learner can see ==="
TABLE_LINES="$(grep -c '^|' problem-statement.md 2>/dev/null || true)"
if [ "${TABLE_LINES:-0}" -ne 0 ]; then
    echo "ERROR: problem-statement.md contains a markdown table (${TABLE_LINES} lines)"
    exit 1
fi
# Word boundaries matter: "the classify step" is not a reference to a class,
# and `class` on its own is a Python keyword.
TEACHY='\b(lecture|grading|grader|canary|sentinel|oracle|fixture)\b|\b(the|this|in) (class|course)\b'
if grep -rilE --include='*.py' --include='*.json' "$TEACHY" app/ >/dev/null 2>&1; then
    echo "ERROR: provided source under app/ reads like teaching material:"
    grep -rilE --include='*.py' --include='*.json' "$TEACHY" app/ | sed 's/^/       /'
    exit 1
fi
INTERNALS='\b(lecture|mock|deterministic|canary|sentinel|oracle|hardcode|hard-code)\b|__on3k|grader-key|\b(the|this|in) (class|course)\b'
if grep -qiE "$INTERNALS" problem-statement.md; then
    echo "ERROR: problem-statement.md leaks an internal or reads like teaching material:"
    grep -niE "$INTERNALS" problem-statement.md | sed 's/^/       /'
    exit 1
fi
# The desk must never be readable under the learner project.
if grep -q 'chmod 700 "\$SVC"' setup/scripts/setup_script.sh; then
    echo "  the wire is installed root-only outside the learner project"
else
    echo "ERROR: the setup script does not lock down the wire directory"
    exit 1
fi
if grep -rq 'wired.py' app/ 2>/dev/null; then
    echo "ERROR: the learner-visible source names the wire implementation"
    exit 1
fi
echo "  provided sources and the statement are clean"
echo
echo "done. Max Score = ${COUNT} x 10"
