#!/bin/bash
# Regenerate setup/scripts/setup_script.sh from the template plus app/ and
# service/, verify every invariant this pack depends on, then stage
# dist/Setup.zip and dist/TestCase.zip from a clean directory so no harness
# file can leak into the test pack.
#
# Both zips carry a scripts/ AND a data/ folder at the root; the platform
# rejects the older scripts-only shape.
set -euo pipefail

DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$DIR"

echo "=== [1/6] expanding setup template ==="
python3 - <<'PY'
import pathlib, re, sys

tpl = pathlib.Path("setup/setup_script.template.sh").read_text()

def expand(match):
    path = pathlib.Path(match.group(1))
    if not path.is_file():
        sys.exit("missing source file referenced by template: %s" % path)
    return path.read_text().rstrip("\n")

out, n = re.subn(r"@@FILE:([^@]+)@@", expand, tpl)
if "@@FILE:" in out:
    sys.exit("unexpanded marker left in generated setup script")
header = "# GENERATED by build.sh from setup/setup_script.template.sh - do not hand-edit.\n"
lines = out.split("\n")
out = lines[0] + "\n" + header + "\n".join(lines[1:])
pathlib.Path("setup/scripts/setup_script.sh").write_text(out)
print("  inlined %d source files" % n)
PY
chmod +x setup/scripts/setup_script.sh
bash -n setup/scripts/setup_script.sh
echo "  setup_script.sh syntax OK"
# The setup script runs on an image with no python3 and busybox coreutils.
# Lines belonging to an inlined Dockerfile or to a python source file are
# fine - those run inside containers. What must not appear is a python
# invocation in the script's own shell.
HOSTPY="$(grep -nE '(^|[^a-zA-Z0-9_/.-])python3? ' setup/scripts/setup_script.sh \
    | grep -vE '^[0-9]+:(#|RUN |CMD |ENTRYPOINT |ENV |FROM )' \
    | grep -vE 'python:3\.11' \
    | grep -vE '^[0-9]+:\s*(#|"|.*""")' || true)"
if [ -n "$HOSTPY" ]; then
    echo "  ERROR: the setup script invokes python on a host that has none:"
    printf '%s\n' "$HOSTPY" | sed 's/^/       /'
    exit 1
fi
if grep -nE 'timeout +-k' setup/scripts/setup_script.sh >/dev/null 2>&1; then
    echo "  ERROR: busybox timeout has no -k; use the cap helper"
    exit 1
fi
echo "  setup script uses only what the target image has"

echo "=== [2/6] checking the pack against its own numbers ==="
python3 - <<'CONSISTCHK'
import importlib.util, json, pathlib, re, sys

spec = importlib.util.spec_from_file_location(
    "matching", "app/depot-api/matching.py")
matching = importlib.util.module_from_spec(spec)
spec.loader.exec_module(matching)

catalogue = json.loads(
    pathlib.Path("app/depot-api/catalog/parts.json").read_text())
parts = catalogue["parts"]

def fnv(text):
    h = 1469598103934665603
    for byte in text.encode("utf-8"):
        h ^= byte
        h = (h * 1099511628211) & 0xFFFFFFFFFFFFFFFF
    return "%016x" % h

gen = pathlib.Path("gen_tests.sh").read_text()
statement = pathlib.Path("problem-statement.md").read_text()

def constant(name, source=gen):
    found = re.search(r'^%s=(?:"([^"]*)"|(\d+))' % name, source, re.M)
    if not found:
        sys.exit("could not read %s from the test generator" % name)
    return found.group(1) or found.group(2)

# The fingerprint the checks assert has to be the fingerprint this catalogue
# actually produces, and the same routine has to be what the C extension
# computes - the C source is the thing shipped, so a drift here is a lab where
# a correct answer scores zero.
want_fp = fnv("|".join(sorted(p["part_no"] for p in parts)))
if constant("CATALOG_FP") != want_fp:
    sys.exit("CATALOG_FP is %s but this catalogue fingerprints to %s"
             % (constant("CATALOG_FP"), want_fp))
probe_in, probe_out = constant("HASH_PROBE_IN"), constant("HASH_PROBE_OUT")
if fnv(probe_in) != probe_out:
    sys.exit("HASH_PROBE_OUT is %s but %r fingerprints to %s"
             % (probe_out, probe_in, fnv(probe_in)))
print("  fingerprint constants agree with the catalogue")

# The counts the checks assert have to be the counts the indexer produces.
tokens = set()
for part in parts:
    tokens.update(matching.tokens(" ".join([part["name"]] + part["keywords"])))
if int(constant("EXPECT_PARTS")) != len(parts):
    sys.exit("EXPECT_PARTS is %s but the catalogue has %d"
             % (constant("EXPECT_PARTS"), len(parts)))
if int(constant("EXPECT_TOKENS")) != len(tokens):
    sys.exit("EXPECT_TOKENS is %s but the catalogue yields %d distinct tokens"
             % (constant("EXPECT_TOKENS"), len(tokens)))
print("  %d parts and %d tokens, matching what the checks expect"
      % (len(parts), len(tokens)))

# Every graded need must resolve to a part, or the check asserts against
# nothing. And a need shown in the statement must never also be graded, or a
# learner who copies the worked example scores for it.
graded = re.findall(r'need="([^"]+)"', gen)
if len(graded) < 2:
    sys.exit("expected at least two graded needs in the generator, found %d"
             % len(graded))
for need in graded:
    part, score = matching.best_match(need, parts)
    if part is None:
        sys.exit("graded need %r resolves to no part at all" % need)
    if need in statement:
        sys.exit("graded need %r is also shown in the problem statement" % need)
    print("    graded need -> %s (score %d)" % (part["part_no"], score))

# The worked example in the statement has to be the answer the statement claims.
shown = re.search(r'"need":"([^"]+)"', statement)
if shown:
    part, _ = matching.best_match(shown.group(1), parts)
    if part is None or part["part_no"] not in statement:
        sys.exit("the worked example in the statement does not resolve to the "
                 "part number the statement prints")
    print("    worked example -> %s (shown in the statement)" % part["part_no"])
CONSISTCHK

echo "=== [3/6] checking test scripts ==="
COUNT=$(ls -1 test-cases/scripts/script_*.sh | wc -l | tr -d ' ')
if [ "$COUNT" -gt 5 ]; then
    echo "  ERROR: $COUNT test scripts - the platform accepts at most 5"
    exit 1
fi
for f in test-cases/scripts/script_*.sh; do
    bash -n "$f"
    grep -q 'trap on_exit EXIT' "$f" || { echo "  $f lacks the single-verdict guarantee"; exit 1; }
    grep -q 'chown -R user:user' "$f" || { echo "  $f does not hand ownership back"; exit 1; }
    for c in CURL_MAX SVC_WAIT UP_BUDGET DOWN_BUDGET BUILD_BUDGET SHIP_BUDGET LOAD_BUDGET DOCK_MAX IMG_WAIT; do
        grep -q "${c}=" "$f" || { echo "  $f has no ${c} budget"; exit 1; }
    done
    grep -q 'probe_cleanup' "$f" || { echo "  $f does not clean up its probe containers"; exit 1; }
    if grep -qE '^\s*set -[eu]' "$f"; then
        echo "  $f uses set -e or set -u; a probe that fails must still reach a verdict"
        exit 1
    fi
    # busybox timeout has no -k, so no script may hardcode it.
    if grep -qE '\btimeout +-k' "$f"; then
        echo "  $f hardcodes timeout -k, which busybox rejects outright"
        exit 1
    fi
done
python3 - <<'PREAMBLECHK'
import pathlib, sys

def preamble(path):
    lines = pathlib.Path(path).read_text().splitlines()
    for index, line in enumerate(lines):
        if line.startswith("preflight_running() {"):
            return "\n".join(lines[2:index + 5])
    sys.exit("could not find the end of the preamble in %s" % path)

paths = sorted(pathlib.Path("test-cases/scripts").glob("script_*.sh"))
first = preamble(paths[0])
for path in paths[1:]:
    if preamble(path) != first:
        sys.exit("the shared preamble has drifted in %s - regenerate with ./gen_tests.sh"
                 % path)
print("  the shared preamble is identical across all %d scripts" % len(paths))
PREAMBLECHK
echo "  $COUNT test scripts syntax OK, each with a bounded time budget"

echo "=== [4/6] staging zips ==="
STAGE="$(mktemp -d)"
trap 'rm -rf "$STAGE"' EXIT
mkdir -p "$STAGE/setup/scripts" "$STAGE/setup/data" \
         "$STAGE/test/scripts"  "$STAGE/test/data"
cp setup/scripts/setup_script.sh "$STAGE/setup/scripts/"
cp test-cases/scripts/script_*.sh "$STAGE/test/scripts/"

mkdir -p dist
rm -f dist/Setup.zip dist/TestCase.zip
( cd "$STAGE/setup" && zip -qr "$DIR/dist/Setup.zip" scripts data )
( cd "$STAGE/test"  && zip -qr "$DIR/dist/TestCase.zip" scripts data )

echo "=== [5/6] verifying zip contents ==="
for z in dist/Setup.zip dist/TestCase.zip; do
    echo "-- $z"
    unzip -Z1 "$z" | sed 's/^/     /'
    grep -q '^scripts/$' <<< "$(unzip -Z1 "$z")" || { echo "ERROR: $z has no scripts/ folder"; exit 1; }
    grep -q '^data/$' <<< "$(unzip -Z1 "$z")"   || { echo "ERROR: $z has no data/ folder"; exit 1; }
done
if grep -qE 'common\.sh|run-all\.sh|\.DS_Store' <<< "$(unzip -Z1 dist/TestCase.zip)"; then
    echo "ERROR: TestCase.zip contains a non-test file"
    exit 1
fi

echo "=== [6/6] checking what the learner can see ==="
TABLE_LINES="$(grep -c '^|' problem-statement.md 2>/dev/null || true)"
if [ "${TABLE_LINES:-0}" -ne 0 ]; then
    echo "ERROR: problem-statement.md contains a markdown table (${TABLE_LINES} lines)"
    exit 1
fi
# `class` on its own is a Python keyword, so the phrases are matched rather
# than the bare word.
for word in lecture "the course" "this course" "the class" "this class" "in class" \
            grading grader canary sentinel oracle "test case"; do
    if grep -ril --include='*.py' --include='*.md' --include='*.txt' -- "$word" app/ >/dev/null 2>&1; then
        echo "ERROR: provided source under app/ mentions '$word'"
        grep -ril --include='*.py' --include='*.md' --include='*.txt' -- "$word" app/ | sed 's/^/       /'
        exit 1
    fi
done
for word in lecture "the course" "this course" "the class" "this class" "in class" \
            mock canary sentinel oracle hardcode "hard-code" "__dep7f2" "depot-ops"; do
    if grep -qi -- "$word" problem-statement.md; then
        echo "ERROR: problem-statement.md mentions '$word'"
        exit 1
    fi
done
# The backend the learner is handed must be an image, never source on disk.
if grep -q 'rm -rf "\$SVC_STAGE"' setup/scripts/setup_script.sh; then
    echo "  the adviser backend build directory is removed after the image is built"
else
    echo "ERROR: the setup script leaves the backend source on disk"
    exit 1
fi
echo "  provided sources and the statement are clean"
echo
echo "done. Max Score = ${COUNT} x 10"
