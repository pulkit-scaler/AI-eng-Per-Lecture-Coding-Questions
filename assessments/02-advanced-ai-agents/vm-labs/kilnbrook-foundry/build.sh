#!/bin/bash
# Regenerate setup/scripts/setup_script.sh from the template plus app/ and service/,
# run every invariant this pack depends on, then stage dist/Setup.zip and
# dist/TestCase.zip from a clean directory so no stub or harness can leak into the
# test pack.
#
# Both zips carry a scripts/ AND a data/ folder at the root; the platform rejects
# the older scripts-only shape.
set -euo pipefail

DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$DIR"

echo "=== [1/7] expanding setup template ==="
python3 - <<'PY'
import pathlib, re, sys

tpl = pathlib.Path("setup/setup_script.template.sh").read_text()

def expand(match):
    path = pathlib.Path(match.group(1))
    if not path.is_file():
        sys.exit("missing source file referenced by template: %s" % path)
    return path.read_text().rstrip("\n")

out, n = re.subn(r"@@FILE:([^@]+)@@", expand, tpl)
if "@@FILE:" in out:
    sys.exit("unexpanded marker left in generated setup script")
header = "# GENERATED by build.sh from setup/setup_script.template.sh - do not hand-edit.\n"
lines = out.split("\n")
out = lines[0] + "\n" + header + "\n".join(lines[1:])
pathlib.Path("setup/scripts/setup_script.sh").write_text(out)
print("  inlined %d source files" % n)
PY
chmod +x setup/scripts/setup_script.sh
bash -n setup/scripts/setup_script.sh
echo "  setup_script.sh syntax OK"

echo "=== [2/7] verifying inlined copies match the pack mirrors ==="
python3 - <<'PY'
import pathlib, re, sys

tpl = pathlib.Path("setup/setup_script.template.sh").read_text()
gen = pathlib.Path("setup/scripts/setup_script.sh").read_text()
wanted = re.findall(r"@@FILE:([^@]+)@@", tpl)
blocks = re.findall(r"<<'___KBFILE___'\n(.*?)\n___KBFILE___\n", gen, re.S)
if len(blocks) != len(wanted):
    sys.exit("expected %d inlined blocks, found %d" % (len(wanted), len(blocks)))
for path, body in zip(wanted, blocks):
    mirror = pathlib.Path(path).read_text().rstrip("\n")
    if body != mirror:
        sys.exit("inlined copy of %s differs from the pack mirror" % path)
print("  %d/%d inlined sources match byte for byte" % (len(blocks), len(wanted)))
PY

echo "=== [3/7] checking the persona is identical on both sides ==="
python3 - <<'PY'
import ast, pathlib, sys

def literal(path, name):
    tree = ast.parse(pathlib.Path(path).read_text())
    for node in tree.body:
        if isinstance(node, ast.Assign):
            for target in node.targets:
                if isinstance(target, ast.Name) and target.id == name:
                    return ast.literal_eval(node.value)
    sys.exit("could not find %s in %s" % (name, path))

kit = literal("app/kiln_kit/persona.py", "PERSONA")
svc = literal("service/foundryd.py", "PERSONA")
if kit != svc:
    sys.exit("PERSONA in app/kiln_kit/persona.py and service/foundryd.py have drifted")
print("  persona matches (role, %d rules, instructions, output_format)"
      % len(kit["rules"]))
PY

echo "=== [4/7] checking the test scripts ==="
COUNT=$(ls -1 test-cases/scripts/script_*.sh | wc -l | tr -d ' ')
if [ "$COUNT" -gt 5 ]; then
    echo "  ERROR: $COUNT test scripts - the platform accepts at most 5"
    exit 1
fi
for f in test-cases/scripts/script_*.sh; do
    bash -n "$f"
    c=$(grep -c 'report "' "$f")
    [ "$c" -ge 2 ] || { echo "  $f has no verdict calls"; exit 1; }
    grep -q 'trap on_exit EXIT' "$f" || { echo "  $f lacks the single-verdict guarantee"; exit 1; }
    grep -q 'chown -R user:user' "$f" || { echo "  $f never hands ownership back"; exit 1; }
    # Every wait a check performs must be bounded, or the portal kills it as a
    # blocking process instead of scoring it.
    grep -q 'RUN_BUDGET=' "$f" || { echo "  $f has no learner-run time budget"; exit 1; }
    grep -q 'SVC_WAIT=' "$f"   || { echo "  $f has no endpoint-wait budget"; exit 1; }
    grep -q 'CURL_MAX=' "$f"   || { echo "  $f has no per-request budget"; exit 1; }
    grep -q 'DEPS_WAIT=' "$f"  || { echo "  $f has no dependency-wait budget"; exit 1; }
    grep -q 'PYTHONDONTWRITEBYTECODE=1' "$f" || { echo "  $f may drop root-owned bytecode"; exit 1; }
    # Judge fidelity. The platform helper installs an ERR trap in this script's own
    # shell; left in place it prints INTERNAL_ERROR after the verdict, the judge
    # grades the last line, and the learner sees no test cases at all. The stderr
    # redirect closes the same hole for a stray line on stderr.
    grep -q '^trap - ERR$' "$f" || { echo "  $f does not drop the inherited ERR trap"; exit 1; }
    grep -q '^set +eE$' "$f"    || { echo "  $f does not clear set -e / set -E"; exit 1; }
    grep -q '^exec 2>>' "$f"    || { echo "  $f does not divert stderr away from the verdict"; exit 1; }
    grep -q 'id -u user' "$f"   || { echo "  $f gates the ownership repair on the wrong thing"; exit 1; }
    grep -q 'run_evidence' "$f" || { echo "  $f names a log without branching on it being empty"; exit 1; }
    if grep -q 'trace_hint' "$f"; then
        echo "  $f still splices the dead trace_hint stub"; exit 1
    fi
done
python3 - <<'PY'
import pathlib, re, sys

scripts = sorted(pathlib.Path("test-cases/scripts").glob("script_*.sh"))

# An apostrophe inside a <<'PY' ... PY body unbalances the whole script, because the
# heredoc sits inside a $( ) command substitution. bash -n reports it far from the
# real line, so it is caught here instead.
for path in scripts + [pathlib.Path("gen_tests.sh")]:
    text = path.read_text()
    for body in re.findall(r"<<'PY'\n(.*?)\nPY\n", text, re.S):
        if "'" in body:
            bad = [ln for ln in body.splitlines() if "'" in ln]
            sys.exit("apostrophe inside a quoted python heredoc in %s: %s"
                     % (path, bad[:2]))
print("  no apostrophes inside any quoted python heredoc")

# The preamble is duplicated on purpose (the platform runs every file in scripts/ as
# a test, so nothing may be sourced). Duplicated means it can drift, so compare it.
def preamble(text):
    lines = text.split("\n")
    for i, line in enumerate(lines):
        if re.match(r"^Test0[1-9]\(\) \{", line):
            return "\n".join(lines[2:i])
    sys.exit("no test function found")

first = preamble(scripts[0].read_text())
for path in scripts[1:]:
    if preamble(path.read_text()) != first:
        sys.exit("the shared preamble in %s has drifted from %s"
                 % (path.name, scripts[0].name))
print("  all %d scripts share a byte-identical preamble" % len(scripts))
PY
echo "  $COUNT test scripts OK, each with a bounded time budget"

echo "=== [5/7] checking the learner-visible surface ==="
if [ "$(grep -c '^|' problem-statement.md || true)" != "0" ]; then
    echo "  ERROR: problem-statement.md contains a markdown table; the portal renderer"
    echo "         collapses those into literal pipe characters. Use bullet lists."
    exit 1
fi
LEAK=0
# The statement may of course talk about being graded; what it must never do is
# describe how the endpoint works or how the checks are anchored.
STATEMENT_TERMS='mock|lecture|lectures|course|canary|sentinel|oracle|deterministic|hardcode'
# The provided sources are read line by line by learners, so they carry the stricter
# list as well as the terms above.
SOURCE_TERMS="${STATEMENT_TERMS}|grader|grading|audit"
check_leak() {   # <file> <pattern>
    grep -niwE "$2" "$1" >/dev/null 2>&1 || return 0
    echo "  ERROR: $1 leaks an internal term:"
    grep -niwE "$2" "$1" | sed 's/^/         /'
    LEAK=1
}
check_leak problem-statement.md "$STATEMENT_TERMS"
for f in app/check_local.py app/solution_stub.py app/kiln_kit/*.py; do
    check_leak "$f" "$SOURCE_TERMS"
done
[ "$LEAK" -eq 0 ] || exit 1
echo "  no markdown tables and no leaked internals in the learner-visible files"

echo "=== [6/7] staging zips ==="
STAGE="$(mktemp -d)"
trap 'rm -rf "$STAGE"' EXIT
mkdir -p "$STAGE/setup/scripts" "$STAGE/setup/data" \
         "$STAGE/test/scripts"  "$STAGE/test/data"
cp setup/scripts/setup_script.sh "$STAGE/setup/scripts/"
cp test-cases/scripts/script_*.sh "$STAGE/test/scripts/"

mkdir -p dist
rm -f dist/Setup.zip dist/TestCase.zip
( cd "$STAGE/setup" && zip -qr "$DIR/dist/Setup.zip" scripts data )
( cd "$STAGE/test"  && zip -qr "$DIR/dist/TestCase.zip" scripts data )

echo "=== [7/7] verifying zip contents ==="
echo "-- Setup.zip"
unzip -Z1 dist/Setup.zip | sed 's/^/     /'
echo "-- TestCase.zip"
unzip -Z1 dist/TestCase.zip | sed 's/^/     /'
# Never put grep -q or head downstream of a producer that has more to say: under
# pipefail the early exit closes the pipe, the producer dies on SIGPIPE and the
# pipeline fails intermittently. Capture first, match against a here-string.
for z in dist/Setup.zip dist/TestCase.zip; do
    listing="$(unzip -Z1 "$z")"
    grep -q '^scripts/$' <<<"$listing" || { echo "ERROR: $z has no scripts/ folder"; exit 1; }
    grep -q '^data/$'    <<<"$listing" || { echo "ERROR: $z has no data/ folder"; exit 1; }
done
tc_listing="$(unzip -Z1 dist/TestCase.zip)"
if grep -qE 'common\.sh|run-all\.sh|\.DS_Store' <<<"$tc_listing"; then
    echo "ERROR: TestCase.zip contains a non-test file"
    exit 1
fi
echo
echo "done. Max Score = ${COUNT} x 10"
