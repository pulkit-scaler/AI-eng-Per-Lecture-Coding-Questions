#!/bin/bash
# Regenerate setup/scripts/setup_script.sh from the template plus app/ and
# service/, then stage dist/Setup.zip and dist/TestCase.zip from a clean
# directory so no stub or harness can leak into the test pack.
#
# Both zips carry a scripts/ AND a data/ folder at the root; the platform
# rejects the older scripts-only shape.
set -euo pipefail

DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$DIR"

echo "=== [1/5] expanding setup template ==="
python3 - <<'PY'
import pathlib, re, sys

tpl = pathlib.Path("setup/setup_script.template.sh").read_text()

def expand(match):
    path = pathlib.Path(match.group(1))
    if not path.is_file():
        sys.exit("missing source file referenced by template: %s" % path)
    return path.read_text().rstrip("\n")

out, n = re.subn(r"@@FILE:([^@]+)@@", expand, tpl)
if "@@FILE:" in out:
    sys.exit("unexpanded marker left in generated setup script")
header = "# GENERATED by build.sh from setup/setup_script.template.sh - do not hand-edit.\n"
lines = out.split("\n")
out = lines[0] + "\n" + header + "\n".join(lines[1:])
pathlib.Path("setup/scripts/setup_script.sh").write_text(out)
print("  inlined %d source files" % n)
PY
chmod +x setup/scripts/setup_script.sh
bash -n setup/scripts/setup_script.sh
echo "  setup_script.sh syntax OK"

echo "=== [2/5] checking sources ==="
python3 - <<'SRCCHK'
import pathlib, re, sys

# The learner-visible surface must not name the teaching context, the checks
# internals, or the fact that the local endpoint is anything but an endpoint.
BANNED = ("lecture", "curriculum", "grading", "grader", "canary", "sentinel",
          "deterministic", "fixed plan", "not a real model")
# "class" on its own is ordinary Python, so only the teaching senses are banned.
BANNED_RE = (r"\bin class\b", r"\bclass \d", r"\bthe classroom\b",
             r"\bcourse\b", r"\bmock(ed|s|ing)?\b", r"\b__stats\b")
visible = sorted(pathlib.Path("app").rglob("*.py"))
visible += [pathlib.Path("problem-statement.md")]
for path in visible:
    if not path.is_file():
        sys.exit("missing learner-visible file: %s" % path)
    lowered = path.read_text().lower()
    for word in BANNED:
        if word in lowered:
            sys.exit("learner-visible file %s mentions %r" % (path, word))
    for pattern in BANNED_RE:
        hit = re.search(pattern, lowered)
        if hit:
            sys.exit("learner-visible file %s matches %r (%r)"
                     % (path, pattern, hit.group(0)))
print("  %d learner-visible files carry no internal wording" % len(visible))

statement = pathlib.Path("problem-statement.md").read_text()
if re.search(r"^\|", statement, re.M):
    sys.exit("problem-statement.md contains a markdown table; the portal renderer "
             "does not support them")
for heading in ("## Scenario", "## What you will build", "## Environment",
                "## Project layout", "## The pieces you are given", "## The data",
                "## Interface contract", "## Your tasks",
                "## Run and verify locally", "## Before you submit"):
    if heading not in statement:
        sys.exit("problem-statement.md is missing the %r section" % heading)
# The grading section hands the learner a reverse-engineering map of the checks.
# "Before you submit" replaces it.
if "## How you are graded" in statement:
    sys.exit("problem-statement.md still describes how it is graded")
for banned in ("10 points", "5 automated checks", "all-or-nothing", "TC01"):
    if banned in statement:
        sys.exit("problem-statement.md leaks check structure: %r" % banned)
# An em dash renders badly and reads as machine-written; the style rule is zero.
if "—" in statement:
    sys.exit("problem-statement.md contains an em dash")
tasks = len(re.findall(r"^### Task \d", statement, re.M))
if tasks < 5:
    sys.exit("problem-statement.md has only %d task sections" % tasks)
print("  problem-statement.md: no tables, no em dashes, no grading section, "
      "%d task sections, all sections present" % tasks)

# The pinned mcp release is the one that still ships mcp.server.fastmcp; the
# fallback rung has to constrain all three packages for the reasons written out
# beside it in the template, or it can install a combination in which every
# correct solution fails.
setup = pathlib.Path("setup/scripts/setup_script.sh").read_text()
for pin in ('"mcp==1.9.4"', '"pydantic-settings==2.14.0"', '"openai==3.1.0"'):
    if pin not in setup:
        sys.exit("the setup script no longer pins %s" % pin)
for bound in ('"mcp>=1.9,<2"', '"pydantic-settings<2.15"', '"openai>=3,<4"'):
    if bound not in setup:
        sys.exit("the setup script fallback rung does not constrain %s" % bound)
if "--only-binary=:all:" not in setup:
    sys.exit("the setup script does not force wheels-only installs")
# Every check shells out to curl and jq, so both have to be installed on the path
# the portal waits on, not only in the detached job.
head = setup.split("=== [2/7]")[0]
for tool in ("curl", "jq"):
    if tool not in head:
        sys.exit("the setup script does not install %s in the foreground" % tool)
print("  setup script pins all three packages, bounds the fallback rung, "
      "and installs curl and jq in the foreground")
SRCCHK

echo "=== [3/5] checking test scripts ==="
COUNT=$(ls -1 test-cases/scripts/script_*.sh | wc -l | tr -d ' ')
if [ "$COUNT" -gt 5 ]; then
    echo "  ERROR: $COUNT test scripts - the platform accepts at most 5"
    exit 1
fi
for f in test-cases/scripts/script_*.sh; do
    bash -n "$f"
    c=$(grep -c 'report "' "$f")
    [ "$c" -ge 2 ] || { echo "  $f has no verdict calls"; exit 1; }
    grep -q 'trap on_exit EXIT' "$f" || { echo "  $f lacks the single-verdict guarantee"; exit 1; }
    # The platform common.sh installs an ERR trap in this shell whose handler
    # prints INTERNAL_ERROR and exits, landing a second line after the verdict.
    # The judge grades the last line, so that voids the whole submission.
    grep -q '^trap - ERR$' "$f" || { echo "  $f does not drop the inherited ERR trap"; exit 1; }
    grep -q '^set +eE$' "$f"    || { echo "  $f does not disable errexit/errtrace"; exit 1; }
    # Same failure mode by a different route: a stray stderr line is graded as the
    # verdict. Keep this script stderr in a file.
    grep -q 'exec 2>>' "$f"     || { echo "  $f does not redirect its own stderr"; exit 1; }
    grep -q 'chown -R user:user' "$f" || { echo "  $f never hands the project back"; exit 1; }
    # The ownership repair must be gated on a learner account existing, not on
    # where LAB_DIR points: gating on the path made it dead code in every
    # environment that tests it.
    grep -q 'id -u user' "$f" || { echo "  $f gates the chown on the wrong condition"; exit 1; }
    # Prevention, not just repair: the checks run the learner code against a copy.
    grep -q 'stage_project' "$f" || { echo "  $f writes into the learner project"; exit 1; }
    # A verdict that names a log must fold in what the log actually holds.
    grep -q 'run_evidence' "$f" || { echo "  $f can name an empty log as evidence"; exit 1; }
    grep -q 'kill_stray_servers' "$f" || { echo "  $f never sweeps up stray MCP servers"; exit 1; }
    grep -q 'PYTHONDONTWRITEBYTECODE' "$f" || { echo "  $f does not suppress bytecode caches"; exit 1; }
    # Every wait a check performs must be bounded, or the portal kills it as a
    # blocking process instead of scoring it.
    grep -q 'RUN_BUDGET=' "$f" || { echo "  $f has no learner-run time budget"; exit 1; }
    grep -q 'SVC_WAIT=' "$f"   || { echo "  $f has no service-wait budget"; exit 1; }
    grep -q 'CURL_MAX=' "$f"   || { echo "  $f has no per-request budget"; exit 1; }
    grep -q 'DEPS_WAIT=' "$f"  || { echo "  $f has no dependency-wait budget"; exit 1; }
done
python3 - <<'HEREDOC'
import pathlib, re, sys

# A heredoc body sits inside a $( ) command substitution, so bash scans its quote
# characters while parsing: a single apostrophe unbalances the whole script and the
# error surfaces on some later, innocent line. Backticks are worse - the OUTER
# unquoted heredoc in gen_tests.sh substitutes them away silently, so the emitted
# python is quietly wrong rather than broken.
bad = []
scripts = sorted(pathlib.Path("test-cases/scripts").glob("script_*.sh"))
blocks = 0
for path in scripts:
    text = path.read_text()
    if "`" in text:
        bad.append("%s contains a backtick" % path)
    for match in re.finditer(r"<<'PY'\n(.*?)\nPY\n", text, re.S):
        blocks += 1
        body = match.group(1)
        for i, line in enumerate(body.splitlines(), 1):
            if "'" in line:
                bad.append("%s: apostrophe in a PY heredoc at body line %d: %s"
                           % (path, i, line.strip()[:70]))
if not blocks:
    bad.append("no PY heredocs found at all - has the emit pattern changed?")
if bad:
    sys.exit("\n".join("  ERROR: " + item for item in bad))
print("  %d python heredocs, no apostrophes and no backticks" % blocks)

# The shared orchestration must be byte-identical in all five scripts, or a fix
# applied to one silently leaves the others behind.
preambles = set()
for path in scripts:
    text = path.read_text()
    head = text.split("\nTest0", 1)[0]
    head = re.sub(r"^# TC\d+ \(10 pts\).*$", "", head, flags=re.M)
    preambles.add(head)
if len(preambles) != 1:
    sys.exit("  ERROR: the five test scripts do not share one preamble")
print("  the five scripts share a byte-identical preamble")
HEREDOC
echo "  $COUNT test scripts syntax OK, each bounded and each handing the project back"

echo "=== [4/5] staging zips ==="
STAGE="$(mktemp -d)"
trap 'rm -rf "$STAGE"' EXIT
mkdir -p "$STAGE/setup/scripts" "$STAGE/setup/data" \
         "$STAGE/test/scripts"  "$STAGE/test/data"
cp setup/scripts/setup_script.sh "$STAGE/setup/scripts/"
cp test-cases/scripts/script_*.sh "$STAGE/test/scripts/"

mkdir -p dist
rm -f dist/Setup.zip dist/TestCase.zip
( cd "$STAGE/setup" && zip -qr "$DIR/dist/Setup.zip" scripts data )
( cd "$STAGE/test"  && zip -qr "$DIR/dist/TestCase.zip" scripts data )

echo "=== [5/5] verifying zip contents ==="
echo "-- Setup.zip"
unzip -Z1 dist/Setup.zip | sed 's/^/     /'
echo "-- TestCase.zip"
unzip -Z1 dist/TestCase.zip | sed 's/^/     /'
# Read each listing once into a variable and match against a here-string. Under
# `pipefail`, `unzip -Z1 ... | grep -q` fails the whole pipeline whenever grep
# exits on its first match and unzip is still writing: unzip takes SIGPIPE, and
# pipefail reports the pipeline as failed even though the match succeeded. It
# raced about one run in five on another pack. No pipe, no race.
for z in dist/Setup.zip dist/TestCase.zip; do
    listing="$(unzip -Z1 "$z")"
    grep -q '^scripts/$' <<<"$listing" || { echo "ERROR: $z has no scripts/ folder"; exit 1; }
    grep -q '^data/$'    <<<"$listing" || { echo "ERROR: $z has no data/ folder"; exit 1; }
done
tc_listing="$(unzip -Z1 dist/TestCase.zip)"
if grep -qE 'common\.sh|run-all\.sh|\.DS_Store' <<<"$tc_listing"; then
    echo "ERROR: TestCase.zip contains a non-test file"
    exit 1
fi
echo
echo "done. Max Score = ${COUNT} x 10"
