#!/bin/bash
# Regenerate setup/scripts/setup_script.sh from the template plus app/ and
# service/, then stage dist/Setup.zip and dist/TestCase.zip from a clean
# directory so no stub or harness can leak into the test pack.
#
# Both zips carry a scripts/ AND a data/ folder at the root; the platform
# rejects the older scripts-only shape.
set -euo pipefail

DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$DIR"

echo "=== [1/5] expanding setup template ==="
python3 - <<'PY'
import pathlib, re, sys

tpl = pathlib.Path("setup/setup_script.template.sh").read_text()

def expand(match):
    path = pathlib.Path(match.group(1))
    if not path.is_file():
        sys.exit("missing source file referenced by template: %s" % path)
    return path.read_text().rstrip("\n")

out, n = re.subn(r"@@FILE:([^@]+)@@", expand, tpl)
if "@@FILE:" in out:
    sys.exit("unexpanded marker left in generated setup script")
header = "# GENERATED by build.sh from setup/setup_script.template.sh - do not hand-edit.\n"
lines = out.split("\n")
out = lines[0] + "\n" + header + "\n".join(lines[1:])
pathlib.Path("setup/scripts/setup_script.sh").write_text(out)
print("  inlined %d source files" % n)
PY
chmod +x setup/scripts/setup_script.sh
bash -n setup/scripts/setup_script.sh
echo "  setup_script.sh syntax OK"

echo "=== [2/5] checking shared source blocks ==="
python3 - <<'SHAREDCHK'
import pathlib, re, sys

def block(path, name):
    text = pathlib.Path(path).read_text()
    found = re.search(r"# ---- shared:%s ----\n(.*?)# ---- /shared:%s ----" % (name, name),
                      text, re.S)
    if not found:
        sys.exit("could not find the shared:%s block in %s" % (name, path))
    return found.group(1)

# The learner renders a result set with the toolkit while the grader computes the
# expected value with the endpoint. If the two renderers drift, a correct solution
# fails on formatting, so the build refuses to ship a mismatch.
pairs = [
    ("formatter", "app/grid_kit/tools.py", "service/gridd.py"),
    ("desks", "app/grid_kit/handlers.py", "service/gridd.py"),
]
for name, left, right in pairs:
    a, b = block(left, name), block(right, name)
    if a != b:
        sys.exit("shared:%s has drifted between %s and %s" % (name, left, right))
    print("  shared:%-10s matches between %s and %s (%d lines)"
          % (name, left, right, len(a.splitlines())))

# Every prompt marker the endpoint dispatches on has to exist in the prompt the
# learner is handed, or a whole task silently falls through to the default reply.
prompts = pathlib.Path("app/grid_kit/prompts.py").read_text()
service = pathlib.Path("service/gridd.py").read_text()
markers = re.findall(r'\("(?:guard|route|refine|critique|draft)",\s*"([^"]+)"\)', service)
if len(markers) != 5:
    sys.exit("expected 5 dispatch markers in service/gridd.py, found %d" % len(markers))
for marker in markers:
    if marker not in prompts:
        sys.exit("dispatch marker %r is not present in app/grid_kit/prompts.py" % marker)
print("  all %d dispatch markers present in the provided prompts" % len(markers))

# The four guard names and the four categories are fixed by the statement, so the
# toolkit and the endpoint must agree on both lists.
for name, pattern in (("guard names", r"GUARD_NAMES = \[([^\]]*)\]"),):
    left = re.search(pattern, prompts)
    right = re.search(pattern, service)
    if not left or not right:
        sys.exit("could not read %s from both files" % name)
    if sorted(re.findall(r'"([^"]+)"', left.group(1))) != \
       sorted(re.findall(r'"([^"]+)"', right.group(1))):
        sys.exit("%s differ between the toolkit and the endpoint" % name)
    print("  %s agree between the toolkit and the endpoint" % name)
SHAREDCHK

echo "=== [3/5] checking test scripts ==="
# The local common.sh has to be at least as strict as the platform's, or local
# validation proves nothing. A convenience stub that only echoes its arguments is
# how the ERR-trap bug reached production unnoticed.
for probe in 'trap .*ERR' 'handle_internal_error' 'jq -n'; do
    grep -qE "$probe" test-cases/scripts/common.sh \
        || { echo "  ERROR: test-cases/scripts/common.sh is not a faithful replica of the platform helper (missing: $probe)"; exit 1; }
done
echo "  common.sh is a faithful replica (ERR trap, internal-error exit, jq output)"
COUNT=$(ls -1 test-cases/scripts/script_*.sh | wc -l | tr -d ' ')
if [ "$COUNT" -gt 5 ]; then
    echo "  ERROR: $COUNT test scripts - the platform accepts at most 5"
    exit 1
fi
for f in test-cases/scripts/script_*.sh; do
    bash -n "$f"
    c=$(grep -c 'report "' "$f")
    [ "$c" -ge 2 ] || { echo "  $f has no verdict calls"; exit 1; }
    grep -q 'trap on_exit EXIT' "$f" || { echo "  $f lacks the single-verdict guarantee"; exit 1; }
    grep -q 'chown -R user:user' "$f" || { echo "  $f does not hand ownership back"; exit 1; }
    # Every wait a check performs must be bounded, or the portal kills it as a
    # blocking process instead of scoring it.
    grep -q 'RUN_BUDGET=' "$f" || { echo "  $f has no learner-run time budget"; exit 1; }
    grep -q 'SVC_WAIT=' "$f"   || { echo "  $f has no endpoint-wait budget"; exit 1; }
    grep -q 'CURL_MAX=' "$f"   || { echo "  $f has no per-call budget"; exit 1; }
    grep -q 'DEPS_WAIT=' "$f"  || { echo "  $f has no dependency-wait budget"; exit 1; }
    grep -q 'PYTHONDONTWRITEBYTECODE=1' "$f" || { echo "  $f may drop root-owned bytecode into the project"; exit 1; }
    # Judge fidelity. The platform helper installs an ERR trap inside this check's
    # own shell, and its handler prints a second line after the verdict. The judge
    # grades the last line, so that second line voids the verdict and the learner
    # sees an empty test-case panel instead of a score. Dropping the trap and
    # sending stderr to a file are the two lines that prevent it, and a check
    # without them is a live production bug, not a style question.
    grep -q '^trap - ERR$' "$f" || { echo "  $f does not drop the platform ERR trap - its verdict can be voided"; exit 1; }
    grep -q '^set +eE$' "$f"    || { echo "  $f does not clear errexit/errtrace"; exit 1; }
    grep -q 'exec 2>>' "$f"     || { echo "  $f does not redirect stderr - a stray stderr line voids its verdict"; exit 1; }
    grep -q 'id -u user' "$f"   || { echo "  $f gates its ownership repair on the wrong thing"; exit 1; }
    grep -q 'run_evidence' "$f" || { echo "  $f can name an empty log as evidence"; exit 1; }
    grep -q 'trace_hint' "$f"   && { echo "  $f still splices the dead trace_hint stub into a message"; exit 1; }
    if grep -qE '^\s*set -[eu]' "$f"; then
        echo "  $f uses set -e or set -u; a probe that fails must still reach a verdict"
        exit 1
    fi
done
# A single apostrophe inside a <<'PY' ... PY body unbalances the surrounding $( )
# command substitution, and the resulting syntax error surfaces on a line that
# looks fine. Enforced here because it is invisible on inspection.
python3 - <<'QUOTECHK'
import pathlib, sys

bad = []
for path in sorted(pathlib.Path("test-cases/scripts").glob("script_*.sh")):
    inside = False
    for number, line in enumerate(path.read_text().splitlines(), 1):
        if not inside and line.strip().endswith("<<'PY'"):
            inside = True
            continue
        if inside and line.strip() == "PY":
            inside = False
            continue
        if inside and "'" in line:
            bad.append("%s:%d: %s" % (path, number, line.strip()))
if bad:
    print("  ERROR: apostrophes inside a python heredoc body:")
    for line in bad:
        print("    " + line)
    sys.exit(1)
print("  no apostrophes inside any python heredoc body")
QUOTECHK
# The preamble is duplicated into every script on purpose, so drift between two of
# them is a real hazard rather than a style question.
python3 - <<'PREAMBLECHK'
import pathlib, sys

def preamble(path):
    lines = pathlib.Path(path).read_text().splitlines()
    for index, line in enumerate(lines):
        if line.startswith("preflight() {"):
            return "\n".join(lines[2:index + 6])
    sys.exit("could not find the end of the preamble in %s" % path)

paths = sorted(pathlib.Path("test-cases/scripts").glob("script_*.sh"))
first = preamble(paths[0])
for path in paths[1:]:
    if preamble(path) != first:
        sys.exit("the shared preamble has drifted in %s - regenerate with ./gen_tests.sh"
                 % path)
print("  the shared preamble is identical across all %d scripts" % len(paths))
PREAMBLECHK
echo "  $COUNT test scripts syntax OK, each with a bounded time budget"

echo "=== [4/5] staging zips ==="
STAGE="$(mktemp -d)"
trap 'rm -rf "$STAGE"' EXIT
mkdir -p "$STAGE/setup/scripts" "$STAGE/setup/data" \
         "$STAGE/test/scripts"  "$STAGE/test/data"
cp setup/scripts/setup_script.sh "$STAGE/setup/scripts/"
cp test-cases/scripts/script_*.sh "$STAGE/test/scripts/"

mkdir -p dist
rm -f dist/Setup.zip dist/TestCase.zip
( cd "$STAGE/setup" && zip -qr "$DIR/dist/Setup.zip" scripts data )
( cd "$STAGE/test"  && zip -qr "$DIR/dist/TestCase.zip" scripts data )

echo "=== [5/5] verifying zip contents ==="
echo "-- Setup.zip"
unzip -Z1 dist/Setup.zip | sed 's/^/     /'
echo "-- TestCase.zip"
unzip -Z1 dist/TestCase.zip | sed 's/^/     /'
# Never put grep -q or head downstream of a producer with more to say while
# pipefail is on. grep -q exits at the first match, which SIGPIPEs unzip, and
# pipefail then reports the whole pipeline as failed - so a zip that is perfectly
# correct is rejected, intermittently, depending on how much unzip had left to
# write. Observed here on TestCase.zip while Setup.zip passed in the same run.
# Capture once, then match against a here-string.
for z in dist/Setup.zip dist/TestCase.zip; do
    LISTING="$(unzip -Z1 "$z")"
    grep -q '^scripts/$' <<<"$LISTING" || { echo "ERROR: $z has no scripts/ folder"; exit 1; }
    grep -q '^data/$'    <<<"$LISTING" || { echo "ERROR: $z has no data/ folder"; exit 1; }
done
TC_LISTING="$(unzip -Z1 dist/TestCase.zip)"
if grep -qE 'common\.sh|run-all\.sh|\.DS_Store' <<<"$TC_LISTING"; then
    echo "ERROR: TestCase.zip contains a non-test file"
    exit 1
fi
# The learner-facing statement is rendered by a viewer with no GFM table support, so
# a table collapses into a wall of pipe characters on their screen.
TABLE_LINES="$(grep -c '^|' problem-statement.md 2>/dev/null || true)"
if [ "${TABLE_LINES:-0}" -ne 0 ]; then
    echo "ERROR: problem-statement.md contains a markdown table (${TABLE_LINES} lines)"
    exit 1
fi
for word in lecture course "class " grading grader mock canary sentinel oracle; do
    if grep -ril --include='*.py' -- "$word" app/ >/dev/null 2>&1; then
        echo "ERROR: provided source under app/ mentions '$word'"
        grep -ril --include='*.py' -- "$word" app/ | sed 's/^/       /'
        exit 1
    fi
done
echo "  provided sources and the statement are clean"
echo
echo "done. Max Score = ${COUNT} x 10"
